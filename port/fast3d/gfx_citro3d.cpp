// Map a Fast3D combiner input to a PICA TEV source. The single per-vertex input
// (typically SHADE) goes to PRIMARY_COLOR; per-draw-constant inputs (PRIM/ENV)
// are folded to a TEV CONSTANT; textures to TEXTURE0/1. See CLAUDE.md §3.2.
// Which N64 cycle the current TEV stage is being built for (set by buildTev).
// SHADER_INPUT_2 is ambiguous on PICA: character models use it in cycle 0 as a
// per-draw CONSTANT (prim/env/factor) — there it must fold to GPU_CONSTANT, or it
// reads garbage from the (empty) PREVIOUS register → flat red models. Level
// geometry uses it in cycle 1 as a SECOND per-vertex lighting colour — folding
// THAT to one constant (from vertex 0) makes the floor/walls flat and twitch as
// batches re-form when the camera moves; there GPU_PREVIOUS (the cycle-0 shade
// result) is the right approximation.
//
// BUT the SAME combiner (e.g. 020d020d818a818a) is also used by the floor light/
// shadow DECALS, where cycle-1 INPUT_2 IS a per-draw constant (the shadow strength:
// cyc1 = COMBINED*INPUT2). Mapping it to PREVIOUS there gives COMBINED*COMBINED ≈
// opaque → the shadow renders stark/"pasted" instead of softly darkening (verified
// against gfx_opengl.cpp: forcing INPUT_2→PREVIOUS in the GL combiner reproduces
// the exact bug). A static per-cycle map can't serve both. So for cycle 1 we build
// TWO chains and pick per-draw by testing whether INPUT_2 varies across the batch
// (the SM64 "two-colour tris" idea): sBuildI2Const selects which chain buildTev
// emits — true → GPU_CONSTANT (folded; constant INPUT_2 → soft shadow), false →
// GPU_PREVIOUS (varying INPUT_2 → stable lighting).
// ★ 8x8 all-white texture, permanently bound to the always-free PICA unit 2.
// Literal SHADER_1 maps to GPU_TEXTURE2 (src operand) and SHADER_0 to
// GPU_TEXTURE2 with a one-minus operand — so literals NEVER occupy the per-stage
// constant register, which stays exclusively for folded per-draw inputs. (The
// intro logo's cyc0 lerp(IN1->white) needed white AND the IN1 fold in ONE stage:
// unsolvable with the single constant, exact with the white texture.) Unit 2's
// texcoords are unrouted by our vshader, but every texel is white, so whatever
// coordinate the raster feeds it samples white.
static C3D_Tex sWhiteTex;
static bool    sWhiteTexOk = false;

static int  sTevCycle = 0;
static bool sBuildI2Const = false;
// sBuildSwap: the SM64 "two-colour tris" swap. PICA carries only ONE interpolated
// vertex colour (PRIMARY). Normally INPUT_1 (shade) is the per-vertex one and goes
// to PRIMARY. But some decals (e.g. the a=0 coverage floor-shadow) instead carry a
// per-vertex GRADIENT in INPUT_2 (shade constant). When that's detected per-draw,
// we swap roles: INPUT_2 → PRIMARY (the varying gradient), INPUT_1 → folded CONSTANT.
static bool sBuildSwap = false;
static GPU_TEVSRC tevSrc(uint8_t input, bool *isConst) {
    *isConst = false;
    switch (input) {
        case SHADER_0:        // value 0: white tex + ONE_MINUS operand (see tevOpRgb/tevOpA)
            if (sWhiteTexOk) return GPU_TEXTURE2;
            *isConst = true; return GPU_CONSTANT;
        case SHADER_1:        // value 1: white tex, plain src operand
            if (sWhiteTexOk) return GPU_TEXTURE2;
            *isConst = true; return GPU_CONSTANT;
        case SHADER_INPUT_1:
            if (sBuildSwap) { *isConst = true; return GPU_CONSTANT; } // swapped: INPUT_1 folded
            return GPU_PRIMARY_COLOR;
        case SHADER_INPUT_2:
            if (sBuildSwap) return GPU_PRIMARY_COLOR; // swapped: INPUT_2 is the per-vertex primary
            if (sTevCycle == 0) { *isConst = true; return GPU_CONSTANT; } // cycle-0 const (character models)
            if (sBuildI2Const) { *isConst = true; return GPU_CONSTANT; }  // cycle-1, INPUT_2 constant per-draw
            return GPU_PREVIOUS; // cycle-1, INPUT_2 varies per-vertex ≈ cycle-0 result
        case SHADER_INPUT_3:
        case SHADER_INPUT_4:
        case SHADER_INPUT_5:
        case SHADER_INPUT_6:
        case SHADER_INPUT_7:  *isConst = true; return GPU_CONSTANT;
        case SHADER_TEXEL0:
        case SHADER_TEXEL0A:  return GPU_TEXTURE0;
        case SHADER_TEXEL1:
        case SHADER_TEXEL1A:  return GPU_TEXTURE1;
        case SHADER_COMBINED: return GPU_PREVIOUS;     // cycle-2 feedback
        default:              *isConst = true; return GPU_CONSTANT;
    }
}

static GPU_TEVOP_RGB tevOpRgb(uint8_t input) {
    // TEXELnA pulls the texture's alpha into the colour pipe
    if (input == SHADER_TEXEL0A || input == SHADER_TEXEL1A)
        return GPU_TEVOP_RGB_SRC_ALPHA;
    // literal 0 = 1 - white (the unit-2 white texture)
    if (input == SHADER_0 && sWhiteTexOk)
        return GPU_TEVOP_RGB_ONE_MINUS_SRC_COLOR;
    return GPU_TEVOP_RGB_SRC_COLOR;
}

static GPU_TEVOP_A tevOpA(uint8_t input) {
    // literal 0 = 1 - white.a in the alpha pipe
    if (input == SHADER_0 && sWhiteTexOk)
        return GPU_TEVOP_A_ONE_MINUS_SRC_ALPHA;
    return GPU_TEVOP_A_SRC_ALPHA;
}

// Build one TEV stage (RGB or alpha pipe, or both) from a combiner formula
// c[4] = {a,b,c,d}, with do_single/do_multiply/do_mix flags.
// cR/cA: this stage's constant-register SOURCE per pipe (in/out, 0xFF = none).
// A pipe referencing TWO different const sources in one stage keeps the first
// (can't be represented — one constant register per stage per pipe-pair).
static void recConst(uint8_t *slot, uint8_t code) {
    if (*slot == 0xFF) *slot = code;
    // else: collision within this pipe+stage — first wins (rare; not seen in BK)
}

static void buildStage(C3D_TexEnv *env, C3D_TexEnvMode pipe, const uint8_t c[4],
                       bool do_single, bool do_multiply, bool do_mix, bool *usesConst,
                       uint8_t *cR, uint8_t *cA) {
    // tevSrc + record which SHADER_* the constant register stands for (per pipe)
    auto SRC = [&](uint8_t in) -> GPU_TEVSRC {
        bool k;
        GPU_TEVSRC s = tevSrc(in, &k);
        if (k) {
            *usesConst = true;
            if (pipe & C3D_RGB)   recConst(cR, in);
            if (pipe & C3D_Alpha) recConst(cA, in);
        }
        return s;
    };
    if (do_single) {
        C3D_TexEnvFunc(env, pipe, GPU_REPLACE);
        C3D_TexEnvSrc(env, pipe, SRC(c[3]), GPU_PRIMARY_COLOR, GPU_PRIMARY_COLOR);
    } else if (do_multiply) {
        C3D_TexEnvFunc(env, pipe, GPU_MODULATE);
        GPU_TEVSRC s0 = SRC(c[0]);
        GPU_TEVSRC s1 = SRC(c[2]);
        C3D_TexEnvSrc(env, pipe, s0, s1, GPU_PRIMARY_COLOR);
    } else if (do_mix) {
        // mix(b, a, c) == (a-b)*c + b  →  INTERPOLATE(a, b, c)
        C3D_TexEnvFunc(env, pipe, GPU_INTERPOLATE);
        GPU_TEVSRC s0 = SRC(c[0]);
        GPU_TEVSRC s1 = SRC(c[1]);
        GPU_TEVSRC s2 = SRC(c[2]);
        C3D_TexEnvSrc(env, pipe, s0, s1, s2);
    } else {
        // general (a-b)*c+d — approximate with MODULATE(a,c) (drop b,d).
        // Rare in PD; a full 2-stage SUBTRACT+MAD path is a future refinement.
        C3D_TexEnvFunc(env, pipe, GPU_MODULATE);
        GPU_TEVSRC s0 = SRC(c[0]);
        GPU_TEVSRC s1 = SRC(c[2]);
        C3D_TexEnvSrc(env, pipe, s0, s1, GPU_PRIMARY_COLOR);
    }
    // operands (handle TEXELnA in colour pipe; SHADER_0 = one-minus on the white tex)
    if (pipe & C3D_RGB) {
        if (do_single)        C3D_TexEnvOpRgb(env, tevOpRgb(c[3]), GPU_TEVOP_RGB_SRC_COLOR, GPU_TEVOP_RGB_SRC_COLOR);
        else if (do_multiply) C3D_TexEnvOpRgb(env, tevOpRgb(c[0]), tevOpRgb(c[2]), GPU_TEVOP_RGB_SRC_COLOR);
        else if (do_mix)      C3D_TexEnvOpRgb(env, tevOpRgb(c[0]), tevOpRgb(c[1]), tevOpRgb(c[2]));
        else                  C3D_TexEnvOpRgb(env, tevOpRgb(c[0]), tevOpRgb(c[2]), GPU_TEVOP_RGB_SRC_COLOR);
    }
    if (pipe & C3D_Alpha) {
        if (do_single)        C3D_TexEnvOpAlpha(env, tevOpA(c[3]), GPU_TEVOP_A_SRC_ALPHA, GPU_TEVOP_A_SRC_ALPHA);
        else if (do_multiply) C3D_TexEnvOpAlpha(env, tevOpA(c[0]), tevOpA(c[2]), GPU_TEVOP_A_SRC_ALPHA);
        else if (do_mix)      C3D_TexEnvOpAlpha(env, tevOpA(c[0]), tevOpA(c[1]), tevOpA(c[2]));
        else                  C3D_TexEnvOpAlpha(env, tevOpA(c[0]), tevOpA(c[2]), GPU_TEVOP_A_SRC_ALPHA);
    }
}

// Build ONE TEV stage chain into dst[6]. Faithful per-cycle TEV: N64 combiner
// cycle N -> PICA TEV stage N. The PICA chains stages through the PREVIOUS
// register, so a 2-cycle combiner's cycle-1 SHADER_COMBINED inputs (mapped to
// GPU_PREVIOUS by tevSrc) read cycle-0's output. This replaced the old
// MODULATE(TEX0,PRIMARY) fallback, which discarded the real combiner (including
// its ALPHA) and made translucent surfaces render as a milky wash (CLAUDE.md §14a).
// The cycle-1 INPUT_2 mapping depends on the caller's sBuildI2Const (see tevSrc).
static void buildTevChain(const struct CCFeatures *cc, C3D_TexEnv dst[6],
                          int *outStages, bool *outUsesConst,
                          uint8_t cRgb[6], uint8_t cA[6]) {
    int ncycles = cc->opt_2cyc ? 2 : 1;
    int stage = 0;
    bool usesConst = false;
    memset(cRgb, 0xFF, 6);
    memset(cA,   0xFF, 6);

    for (int cyc = 0; cyc < ncycles && stage < 6; cyc++, stage++) {
        sTevCycle = cyc; // tevSrc maps SHADER_INPUT_2 per-cycle (see its comment)
        C3D_TexEnv *env = &dst[stage];
        C3D_TexEnvInit(env);
        C3D_TexEnvColor(env, 0xFFFFFFFF);

        if (cc->opt_alpha && !cc->color_alpha_same[cyc]) {
            buildStage(env, C3D_RGB,   cc->c[cyc][0], cc->do_single[cyc][0],
                       cc->do_multiply[cyc][0], cc->do_mix[cyc][0], &usesConst,
                       &cRgb[stage], &cA[stage]);
            buildStage(env, C3D_Alpha, cc->c[cyc][1], cc->do_single[cyc][1],
                       cc->do_multiply[cyc][1], cc->do_mix[cyc][1], &usesConst,
                       &cRgb[stage], &cA[stage]);
        } else {
            buildStage(env, C3D_Both,  cc->c[cyc][0], cc->do_single[cyc][0],
                       cc->do_multiply[cyc][0], cc->do_mix[cyc][0], &usesConst,
                       &cRgb[stage], &cA[stage]);
        }
    }

    // Force opaque alpha when the combiner has no alpha output. Patch the LAST
    // stage (the final result the PICA outputs) so 2-cycle chains get alpha=1 too.
    // White-tex alpha (=1) keeps the constant register free for folded inputs;
    // GPU_CONSTANT fallback records SHADER_1 so the per-stage compose feeds 0xFF.
    if (!cc->opt_alpha && stage > 0) {
        C3D_TexEnv *env = &dst[stage - 1];
        C3D_TexEnvFunc(env, C3D_Alpha, GPU_REPLACE);
        if (sWhiteTexOk) {
            C3D_TexEnvSrc(env, C3D_Alpha, GPU_TEXTURE2, GPU_PRIMARY_COLOR, GPU_PRIMARY_COLOR);
            C3D_TexEnvOpAlpha(env, GPU_TEVOP_A_SRC_ALPHA, GPU_TEVOP_A_SRC_ALPHA, GPU_TEVOP_A_SRC_ALPHA);
        } else {
            C3D_TexEnvSrc(env, C3D_Alpha, GPU_CONSTANT, GPU_PRIMARY_COLOR, GPU_PRIMARY_COLOR);
            recConst(&cA[stage - 1], SHADER_1);
        }
    }

    *outStages = stage;
    *outUsesConst = usesConst;
}

static void buildTev(struct ShaderProgram *prg) {
    const struct CCFeatures *cc = &prg->cc;
    int stages;

    // env[] : INPUT_1->PRIMARY, cycle-1 INPUT_2 -> GPU_PREVIOUS (both vary; approx)
    sBuildI2Const = false; sBuildSwap = false;
    buildTevChain(cc, prg->env, &stages, &prg->uses_const, prg->cRgbSrc[0], prg->cASrc[0]);
    // envC[]: INPUT_1->PRIMARY, cycle-1 INPUT_2 -> GPU_CONSTANT (INPUT_2 constant)
    sBuildI2Const = true;  sBuildSwap = false;
    buildTevChain(cc, prg->envC, &stages, &prg->uses_constC, prg->cRgbSrc[1], prg->cASrc[1]);
    // envS[]: INPUT_2->PRIMARY, INPUT_1 -> GPU_CONSTANT (INPUT_2 the varying colour)
    sBuildI2Const = false; sBuildSwap = true;
    buildTevChain(cc, prg->envS, &stages, &prg->uses_constS, prg->cRgbSrc[2], prg->cASrc[2]);
    sBuildI2Const = false; sBuildSwap = false;
    prg->num_stages = stages;

    // ★ DISTANCE FOG (3DS) — append a fog blend as the FINAL TEV stage to all three chains. This is THE 3DS
    //   fog path (it fully replaces the PICA fixed-function FogLut for game geometry — see the §FOG block in
    //   applyCmdState). The PICA's hardware fog unit indexes the FogLut by the f24 `1/w` value, whose coarse
    //   precision at distance BANDS / drops fog on far geometry; computing the fog factor in f32 (per-vertex,
    //   like the PC/GL backend) and feeding the TEV a [0,1] value sidesteps that entirely.
    //   out.rgb = INTERPOLATE(CONSTANT[fogColor], PREVIOUS, factor) = fogColor·f + prev·(1−f). The FACTOR
    //   source is chosen PER DRAW in the repack: PRIMARY.alpha for a per-vertex-fog draw, or this stage's own
    //   CONSTANT.alpha for a per-draw-fog draw (see perVertexFog/perDrawFog). alpha = PREVIOUS (untouched, so
    //   alpha-test/blend still see the combiner's real alpha). Appended only when there's a free stage (PICA
    //   has 6; Turok combiners use ≤4, so room) — the rare 6-stage opt_fog combiner falls back to the FogLut.
    prg->fog_stage = 0xff;
    /* ★ FOG STAGE CLAMP (Lost City GPU-wedge fix + A/B): append the TEV fog stage only to combiners with
     * FEWER than `fogclamp` stages; busier combiners fall back to the PICA hardware FogLut at replay
     * (applyCmdState ~:2554) = PD's exact fog path. Stock fogclamp=6 (any draw with a free stage gets TEV
     * fog, so a 5-stage combiner becomes a 6-stage = the PICA ceiling — the costliest, most fault-prone
     * case). Lower it (e.g. 4) so dense fogged levels can't run the GPU to the stage limit while the common
     * simple draws keep the good f32 fog. `fog 0` (g_cfg_fog) forces all-FogLut. Read at program-build time
     * → set in turok.cfg and relaunch. */
    if (cc->opt_fog && stages < g_cfg_fogclamp && g_cfg_fog) {
        C3D_TexEnv *chains[3] = { &prg->env[stages], &prg->envC[stages], &prg->envS[stages] };
        for (int c = 0; c < 3; c++) {
            C3D_TexEnv *e = chains[c];
            C3D_TexEnvInit(e);
            C3D_TexEnvSrc(e, C3D_RGB, GPU_CONSTANT, GPU_PREVIOUS, GPU_PRIMARY_COLOR);
            C3D_TexEnvOpRgb(e, GPU_TEVOP_RGB_SRC_COLOR, GPU_TEVOP_RGB_SRC_COLOR, GPU_TEVOP_RGB_SRC_ALPHA);
            C3D_TexEnvFunc(e, C3D_RGB, GPU_INTERPOLATE);
            C3D_TexEnvSrc(e, C3D_Alpha, GPU_PREVIOUS, GPU_PREVIOUS, GPU_PREVIOUS);
            C3D_TexEnvOpAlpha(e, GPU_TEVOP_A_SRC_ALPHA, GPU_TEVOP_A_SRC_ALPHA, GPU_TEVOP_A_SRC_ALPHA);
            C3D_TexEnvFunc(e, C3D_Alpha, GPU_REPLACE);
        }
        prg->fog_stage = stages;
        prg->num_stages = stages + 1;
    }

    // cyc1UsesI2: env vs envC differ only if cycle 1 references INPUT_2.
    // usesI2: INPUT_2 referenced anywhere → the envS swap is a candidate.
    prg->cyc1UsesI2 = false;
    prg->usesI2 = false;
    for (int cyc = 0; cyc < 2; cyc++)
        for (int j = 0; j < 2; j++)
            for (int k = 0; k < 4; k++)
                if (cc->c[cyc][j][k] == SHADER_INPUT_2) {
                    prg->usesI2 = true;
                    if (cyc == 1) prg->cyc1UsesI2 = true;
                }
}

static uint8_t computeNumFloats(const struct CCFeatures *cc) {
    uint8_t n = 4; // pos
    for (int i = 0; i < 2; i++) {
        if (cc->used_textures[i]) {
            n += 2;
            if (cc->clamp[i][0]) n += 1;
            if (cc->clamp[i][1]) n += 1;
        }
    }
    if (cc->opt_fog) n += 4;
    if (cc->opt_grayscale) n += 4;
    n += cc->num_inputs * (cc->opt_alpha ? 4 : 3);
    return n;
}

static void computeOffsets(struct ShaderProgram *prg) {
    const struct CCFeatures *cc = &prg->cc;
    uint8_t o = 4; // after pos
    prg->off_uv0 = 0xff; prg->off_uv1 = 0xff; prg->off_input1 = 0xff; prg->off_fog = 0xff;
    if (cc->used_textures[0]) {
        prg->off_uv0 = o; o += 2;
        if (cc->clamp[0][0]) o += 1;
        if (cc->clamp[0][1]) o += 1;
    }
    if (cc->used_textures[1]) {
        prg->off_uv1 = o; o += 2;
        if (cc->clamp[1][0]) o += 1;
        if (cc->clamp[1][1]) o += 1;
    }
    if (cc->opt_fog) { prg->off_fog = o; o += 4; }   // [r,g,b,factor]; per-vertex fog reads factor @ +3
    if (cc->opt_grayscale) o += 4;
    if (cc->num_inputs > 0) prg->off_input1 = o;
}

