// ★ PICA texcoord precision fix. At large UV magnitude the PICA quantises the
// interpolated coordinate (verified: a +64 UV bias renders tiled textures flat;
// a building tiled ~13x reaches |uv|~13 → adjacent pixels sample the same texel →
// vertical bands, and the derivative collapses so mipmaps never engage). Fix:
// tessellate any triangle whose UV span on a *tiling* (repeat/mirror) axis exceeds
// UV_SPAN_MAX, then subtract a per-leaf EVEN integer UV offset so the sampled
// coordinate stays near origin. Even offsets wrap identically for repeat (period
// 1) AND mirror (period 2) → seamless; the midpoint split is exact in clip space.
#ifndef UV_SPAN_MAX
#define UV_SPAN_MAX        1.5f   // overridable via EXTRA_DEFINES for tess experiments
#endif
#ifndef UV_TESS_MAXDEPTH
#define UV_TESS_MAXDEPTH   7
#endif
// ════════════════════════════════════════════════════════════════════════════════
// ★ Pre-tile "bake" for heavily-tiled facades — THE BUILDING-STRIPE FIX. See CLAUDE.md §21.
// ════════════════════════════════════════════════════════════════════════════════
// PROBLEM: a small POT texture tiled 5–44× across a building wall stripes at glancing angles on
// the PICA200 (no anisotropic filtering + f24 texcoord path; the foreshortened band's V deltas
// collapse). PC GL is clean only because it has mips + 4× aniso, which the PICA lacks (§20.2).
//
// FIX: redirect such a draw to a FROZEN texture = the source pre-tiled Nu×Nv, sampled at residual
// UV (÷N → ~0..1) + the bake's own CPU box-filtered mip chain. Small sample UV → the PICA's
// auto-LOD finally engages → the mip area-averages the minified band → no stripes.
//
// ★ THE ARCHITECTURE THAT MAKES IT FLARE-SAFE (the whole reason this version ships where the
//   earlier per-draw bakes failed, §20.19): the renderer does NOT decide "is this draw a facade?"
//   — at draw time a facade and a lens flare are indistinguishable, and guessing gridded the
//   flares. Instead the LEVEL LOADER identifies facades by scanning STATIC room geometry
//   (bg.c pdFacadeScanGdl). Flares/glares are appended at RENDER time + use a dedicated texture
//   set, so they're physically NOT in the scanned mesh → can never be registered → never baked.
//   Flow: bg.c registers (by source addr) → gfx_pc import_texture arms by addr (pdFacadeArmUpload)
//   → upload_texture (here) CREATES the bake → draw_triangles REUSES it (createOK=FALSE, never
//   creates). No draw-time fallback = nothing to misclassify.
//
// ★ PRE-WARM (the pacing fix): bake CREATION is expensive on the ARM11. bg.c pdFacadePrewarmRoom
//   runs each room's geometry through gfx_run_dl in a DECODE-ONLY pass at room LOAD (see
//   gfx_citro3d_set_decode_only below + gfx_pc gfx_run_dl_decode_only), so facades bake before
//   they're drawn instead of in the frame the city first appears.
//
// Baked textures are GPU_RGBA4 (16-bit) — invisible on a
// NO eviction (eviction of a still-visible bake was the "reverts as you navigate" bug).
//   * gen_mipmaps (N64 tex_lod) gates which textures are bake candidates → ONLY facades
//     (flares/glints/HUD are never tex_lod → never baked → can't be tiled into a grid).
//   * NO eviction: cap holds a whole level's facades; when full, SKIP (never evict).
//   * DEFERRED frees: never C3D_TexDelete a baked slot mid-record (replay still binds it
//     → "textures broke on room transition"); queue + free at the next start_frame.
//   * invalidate_texture_cache hook drops all bakes on a gfx_pc cache wipe (no orphan leak).
#define MIP_MAX         256   // a bake gets a mip chain only if pw*ph <= MIP_MAX^2. 512→256: the bake
                              // scratch (sMipLin0/1 = MIP_LIN_TEXELS u32 each) was 1 MB×2; at 256 it's
                              // 256 KB×2 → reclaims ~1.5 MB of the scarce FCRAM linear heap so facade
                              // bakes don't OOM-skip on real HW (bakes are ≤256² by default anyway; only
                              // 256–512² textures lose the §21.11 general tex_lod mips — a subtle effect).
#define MIP_LIN_TEXELS  (MIP_MAX * MIP_MAX)
#define BAKE_MAXDIM     1024  // per-axis cap (PICA limit); total texels also <= MIP_LIN_TEXELS
#define BAKE_CAP        256   // max live bakes — raised so a WHOLE level's facade set is held
                              // WITHOUT eviction (the "stripes on return as I roam" cause was the
                              // 128 cap reclaiming stale entries → recreate-stripe on return).
                              // Downsample-to-fit bakes are small (~55 KB avg) so this is cheap.
#define BAKE_RESERVE    512   // > 2*BAKE_CAP; dedicated bake-only slots (deferred-free headroom)
#define BAKE_MEM_BUDGET (26u * 1024u * 1024u) // FCRAM ceiling for bakes. ★ 14→26 MB once the linear heap was
                              // grown to 48 MB (sys_3ds.c __ctru_linear_heap_size) — a full level's FULL
                              // native-res facade set is ~20 MB; 26 MB fits it with no skips + a healthy floor,
                              // so the 128px square-bake cap could be dropped (full native density everywhere).
                              // (history) ★ Raised 10→14 MB (2026-06-08):
                              // the memlog proved a full level's facade set is ~11 MB and hit the old 10 MB
                              // ceiling → bakeSkip=4 → those facades render RAW (f24 stripe/blur), which one
                              // gets skipped depends on encounter order → INTERMITTENT blur worsening over a
                              // session, cleared by a power-cycle. The ceiling is a CAP, not a reservation —
                              // it only consumes what the level's facades actually need (~11 MB), so the free
                              // floor barely moves (~6.8→~6.3 MB) while every facade now bakes. Beyond it,
                              // skip→raw (never OOM; the §23.2 guards catch genuine FCRAM exhaustion).
#define BAKE_PERFRAME   16    // max NEW bakes/frame (fast recovery after a cache wipe). The "HW stall"
                              // this was lowered to 2 to chase turned out to be the PD_DEBUG3DS SD-card
                              // boot.log writes (per-draw FACEDRAW diag + log bursts), NOT bake creation
                              // — a PD_DEBUG3DS=0 production build is smooth at 16. The pending-bake
                              // queue added for the same phantom was reverted with this (pre-warm bakes
                              // a streamed room's facades in one go at load, as §21.4 intended).
#define BAKE_SPAN_MIN   3.0f  // CREATE a bake only when a surface tiles MORE than this. Raised 1.9→3.0:
                              // dramatic stripes are heavy tiling (5–44×); 2–3× barely stripes, so baking
                              // it wasted the 10 MB budget (starving real facades → they striped) AND
                              // softened moderate NEAR interior panels. 3.0 targets the real offenders and
                              // lets a whole level's facades fit the budget. Runtime A/B via bakespan.txt.
#define BAKE_SRC_MAX    128   // only keep/bake small source textures (the tiled facades)
#define TEX_POOL_USABLE (TEX_POOL_SIZE - BAKE_RESERVE) // gfx_pc allocates only below this

// Stereo shear (per-eye, scaled by the 3D slider). The per-eye horizontal disparity is
// SHEAR_Z*(z/w) + SHEAR_W. SHEAR_Z is the depth-proportional term; SHEAR_W is the CONSTANT
// convergence term that survives the perspective divide and moves the zero-disparity (screen)
// plane OFF the far plane onto mid-scene — without it (W=0) the whole level converges at the
// far plane and, because z/w is 1/z-compressed, collapses to ~0 disparity = FLAT geometry,
// leaving only the near-plane HUD with depth. (sm64_3ds uses the same shear with a non-zero
// w-term = 1/iodW.) Convergence depth: z/w = -SHEAR_W/SHEAR_Z. Mandarine reads the slider as 0
// (mono), so these are tunable ONLY on real hardware — exposed via turok.cfg stereo_z/stereo_w.
// ★ Matched to Forsaken's off-axis stereo SHAPE (disparity strongest at near, falling toward far).
// SHEAR_Z = depth/pop strength; SHEAR_W = the constant convergence term. Convergence (zero-disparity)
// depth = where SHEAR_Z*NDCz = -SHEAR_W, i.e. NDCz = -SHEAR_W/SHEAR_Z. For Turok's near=16/far=1024,
// NDCz = 0.0159 - 16.25/depth, so W/Z=0.06 -> NDCz=-0.06 -> convergence ~190u (out past the look-at
// band; near pops out, far recedes). NOTE: SHEAR_W=0.012 (the earlier value) wrongly put convergence at
// ~51u, FLATTENING the play band — that is why it "looked the same". Keep SHEAR_Z POSITIVE (a negative
// value inverts depth -> near recedes = pseudoscopic). Tune on HW via turok.cfg stereo_z/stereo_w.
#define STEREO_SHEAR_Z 0.10f
#define STEREO_SHEAR_W 0.006f
static float sShearZ = STEREO_SHEAR_Z;   // runtime copies (turok.cfg override; swept on HW, no rebuild)
static float sShearW = STEREO_SHEAR_W;
// ★ turok.cfg stereo_swap: negate the per-eye shear to invert depth (fixes a pseudoscopic "far looks near"
// report). 1.0 (default) = current HW-tuned convention; -1.0 = swapped. Applied in buildTransform; mono
// (eyeSign=0) is inert. The eye→panel mapping (sTopLeft→GFX_LEFT/…) is standard-correct and NOT touched.
static float sEyeSwap = 1.0f;

