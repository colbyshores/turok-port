struct ShaderProgram {
    uint64_t shader_id0;
    uint32_t shader_id1;
    struct CCFeatures cc;
    uint8_t  num_floats;       // source stride in buf_vbo
    uint8_t  num_stages;       // active TEV stages
    bool     uses_const;       // env[]  references a folded constant
    bool     uses_constC;      // envC[] references a folded constant
    bool     uses_constS;      // envS[] (swap) references a folded constant
    bool     cyc1UsesI2;       // cycle-1 references INPUT_2 (env vs envC differ)
    bool     usesI2;           // INPUT_2 referenced anywhere (swap candidate)
    uint8_t  diagLogged;       // DIAG: one-shot per-shader decal log guard
    // Source-layout offsets (floats) into buf_vbo, computed once:
    uint8_t  off_uv0;          // tex0 u (0xff if none)
    uint8_t  off_uv1;          // tex1 u (0xff if none)
    uint8_t  off_input1;       // first colour input (0xff if none)
    uint8_t  off_fog;          // fog block in buf_vbo (0xff if none): [r,g,b,FACTOR]; factor at +3
    uint8_t  fog_stage;        // ★ distance fog: index of the appended fog INTERPOLATE stage, 0xff if none.
                               // The fog colour is the per-draw stageConst[fog_stage]; the factor source is
                               // PRIMARY.alpha (per-vertex) or this stage's CONSTANT.alpha (per-draw).
    // Three precomputed stage chains differing only in how INPUT_1/INPUT_2 map to
    // the single PICA vertex colour (see tevSrc). draw_triangles picks per-draw by
    // testing which input actually varies across the batch (SM64 two-colour tris):
    //   env  : INPUT_1→PRIMARY, cycle-1 INPUT_2→GPU_PREVIOUS (both vary; approx)
    //   envC : INPUT_1→PRIMARY, cycle-1 INPUT_2→GPU_CONSTANT (INPUT_2 constant)
    //   envS : INPUT_2→PRIMARY, INPUT_1→GPU_CONSTANT          (INPUT_2 varies, I1 const)
    // The folded constant is patched per-draw into the chosen chain.
    C3D_TexEnv env[6];
    C3D_TexEnv envC[6];
    C3D_TexEnv envS[6];
    // ★ Per-stage TEV constant SOURCES, per chain (0=env, 1=envC, 2=envS).
    // PICA has one constant register PER STAGE (C3D_SetTexEnv(i,..) writes it),
    // but the old code patched EVERY stage with ONE folded color — so a 2-cycle
    // combiner whose stage 0 needs the literal white and whose stage 1 needs the
    // folded INPUT_3 (the intro's blue N64 logo: cyc1 = COMB*IN3) rendered BLACK.
    // These record WHICH SHADER_* source each stage's constant register stands
    // for (0xFF = none); draw_triangles composes the per-stage VALUES per draw.
    uint8_t cRgbSrc[3][6];
    uint8_t cASrc[3][6];
};

static std::unordered_map<uint64_t, struct ShaderProgram> sShaderPool;
static struct ShaderProgram *sCurShader = NULL;

static inline uint64_t shaderKey(uint64_t id0, uint32_t id1) {
    return id0 ^ ((uint64_t)id1 << 1) ^ ((uint64_t)id1 << 33);
}

