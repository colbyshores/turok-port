// gfx_pc wiped its texture cache (periodic / level load / G_INVALTEXCACHE_EXT): every id was
// orphaned to gfx_pc's free list WITHOUT a delete_texture. ★ With CONTENT-KEYED bakes we do
// NOT drop the bakes here — they live in the registry by content hash and SURVIVE the wipe.
// We only free the per-slot kept SOURCES (their slots are orphaned); when facades re-import
// they re-derive the same hash and RE-USE their existing bake → no rebuild, no twitch, no
// freeze. (Stale cross-level registry bakes are reclaimed lazily by regAlloc's LRU.)
static void gfx_citro3d_invalidate_texture_cache(void) {
    sBakeClears++;
#if PD_DEBUG3DS
    { char bb[64]; snprintf(bb, sizeof(bb), "INVALIDATE f=%u clears=%u", (unsigned)sBakeFrame, (unsigned)sBakeClears); plat3dsBootLog(bb); }
#endif
    for (int i = 1; i < TEX_POOL_SIZE; i++) {
        if (sBakeSrc[i]) { free(sBakeSrc[i]); sBakeSrc[i] = NULL; sBakeSrcW[i] = 0; sBakeSrcH[i] = 0; }
        sBakeHash[i] = 0;
        /* ★ LEAK FIX (Lost City teleporter drift): gfx_pc wipes its texture cache on every level reset and
         * orphans all ids into free_texture_ids, but a normal pool slot's C3D_Tex linear allocation is only
         * reclaimed when that exact id is later reused (upload_texture's C3D_TexDelete-before-init, :1519).
         * Slots not reused by the next level kept their FCRAM forever -> ~0.5-1 MB leaked per teleporter
         * reload (boot.log linFreeKB 49->35 MB over 21 reloads). Free EVERY live pool texture on the wipe so
         * the linear heap fully recovers each reset; gfx_pc re-uploads what the new level needs (each upload
         * re-inits the slot, and sees sTexValid=false here so it won't double-delete). Bakes are below. */
        if (i < TEX_POOL_USABLE && sTexValid[i]) { C3D_TexDelete(&sTexPool[i]); sTexValid[i] = false; }
    }
}

