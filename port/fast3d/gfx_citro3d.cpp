/*
 * gfx_citro3d.cpp — Perfect Dark Fast3D rendering backend for the Nintendo 3DS
 * (PICA200, via Citro3D). Implements `struct GfxRenderingAPI`, replacing the
 * OpenGL backend (gfx_opengl.cpp). See CLAUDE.md for the full design.
 *
 * Pipeline summary:
 *   - Fast3D (gfx_pc.cpp) transforms verts to clip space on the CPU and hands us
 *     a variable-stride `buf_vbo`. We REPACK each vertex into a fixed 10-float
 *     layout (pos4, uv2, rgba4) in a linearAlloc streaming VBO, and RECORD a
 *     DrawCmd (vbo range + render state). Nothing is drawn during the frame.
 *   - At end_frame we REPLAY the recorded command list once per eye, changing
 *     only the vertex-shader `transform` uniform (panel-rotation * depth-remap *
 *     per-eye stereo shear). Geometry is uploaded once → single-pass stereo.
 *   - The N64 colour combiner is translated to PICA TEV stages, precomputed per
 *     ShaderProgram (gfx_cc), with per-draw constant folding.
 *   - Textures: N64 RGBA32 → Morton/Z-order tiled ABGR8, POT-rounded, max 1024.
 *
 * The 3 render targets (top-left, top-right, bottom) live in gfx_3ds.c and are
 * created before this backend's init() runs.
 */

