// bkPortFbSnap — fill the game's CPU framebuffer (gFramebuffers, w*h RGBA16)
// with the LAST PRESENTED frame, for game code that READS the framebuffer
// (falling-jiggies transition: model_copyFramebufferToTextures). Called from
// the game update, i.e. MID-frame: C3D_FrameBegin(SYNCDRAW) already drained
// the GPU and this frame's commands are only queued, so the top target's
// colorBuf still holds the last presented frame (same insight as the fb-dump).
// GX_DisplayTransfer untiles VRAM->linear (GPU DMA — the CPU never touches
// VRAM), then the linear copy is mapped back through the fullscreen-stretch:
// game-fb content occupies X[0,292) rows[0,216) of 320x240 and was stretched
// to the full 400x240 panel; raw layout is portrait 240x400, logical (sx,sy) =
// lin[sx*240 + (239-sy)], bytes A,B,G,R (see /tmp/fb2png.py).
// Pixels are stored PRE-SWAPPED (see bk_gfx.c: the renderer's RGBA16 import
// reads texel payloads as BIG-ENDIAN; the game stores these u16s natively).
extern "C" int bkPortFbSnap(uint16_t *dst, int w, int h) {
    C3D_RenderTarget *t = (C3D_RenderTarget *)gfx3dsTopTarget(0);
    if (!t || !t->frameBuf.colorBuf || !dst || w <= 0 || h <= 0) return -1;
    u32 *lin = (u32 *)linearAlloc(240 * 400 * 4);
    if (!lin) return -1;
    /* ★ Completion detection by SENTINEL, not gspWaitForPPF(): a PPF event from
     * the previous present's display transfer can already be SIGNALED, so a
     * plain wait returns before OUR transfer has written a byte and the loop
     * below reads uninitialized memory (= black pieces). Stamp the buffer's
     * corners, queue the transfer, then poll until the GPU overwrites them
     * (bounded — a wedged transfer falls through after ~100ms with garbage
     * rather than stalling the game like a crash). */
    volatile u32 *s0 = &lin[0], *s1 = &lin[240 * 400 - 1];
    *s0 = 0xDEADBEEF; *s1 = 0xDEADBEEF;
    GSPGPU_FlushDataCache(lin, 240 * 400 * 4);
    GX_DisplayTransfer((u32 *)t->frameBuf.colorBuf, GX_BUFFER_DIM(240, 400),
                       lin, GX_BUFFER_DIM(240, 400),
                       GX_TRANSFER_IN_FORMAT(GX_TRANSFER_FMT_RGBA8) |
                       GX_TRANSFER_OUT_FORMAT(GX_TRANSFER_FMT_RGBA8) |
                       GX_TRANSFER_OUT_TILED(0) | GX_TRANSFER_FLIP_VERT(0) |
                       GX_TRANSFER_RAW_COPY(0) |
                       GX_TRANSFER_SCALING(GX_TRANSFER_SCALE_NO));
    for (int spin = 0; spin < 100; spin++) {
        svcSleepThread(1000000); /* 1 ms */
        GSPGPU_InvalidateDataCache(lin, 240 * 400 * 4);
        if (*s0 != 0xDEADBEEF && *s1 != 0xDEADBEEF) break;
    }
    for (int y = 0; y < h; y++) {
        for (int x = 0; x < w; x++) {
            uint16_t out = 1; // outside the content region: black, alpha set
            if (x < 292 && y < 216) {
                int sx = (x * 400) / 292; if (sx > 399) sx = 399;
                int sy = (y * 240) / 216; if (sy > 239) sy = 239;
                u32 px = lin[(size_t)sx * 240 + (239 - sy)];
                u32 r = (px >> 24) & 0xff, g = (px >> 16) & 0xff, b = (px >> 8) & 0xff;
                out = (uint16_t)(((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | 1);
            }
            dst[(size_t)y * w + x] = (uint16_t)((out << 8) | (out >> 8));
        }
    }
    linearFree(lin);
    BK_TR(BK_TR_PRESENT, "bkPortFbSnap: %dx%d filled from colorBuf", w, h);
    return 0;
}

