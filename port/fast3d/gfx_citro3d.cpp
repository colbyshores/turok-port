#if PD_DEBUG3DS
// ── PERF PROFILE (perf spec, BACKEND-ONLY): per-frame ARM11 macro-phase breakdown, ticks→µs. Pure
//    svcGetSystemTick brackets — no shared code touched, no numerics changed. Phases:
//      game    = sim + display-list build (everything between one present and the next frame's start)
//      interp  = gfx_run_dl: the SHARED gfx_pc DL interpretation + per-vertex MVP + draw recording
//      replay  = per-eye replayCommands (the backend's C3D draw submission)
//      present = C3D_FrameEnd (GPU work + vsync wait = IDLE). present≈0 ⇒ CPU-bound; present large ⇒ not.
//    Logged every 60 frames as a `PROF ...` line. This answers "where does the ARM11 frame time go?".
static u64 sProfStart = 0, sProfEFStart = 0, sProfLastFinish = 0;
static u64 sProfGame = 0, sProfInterp = 0, sProfReplay = 0, sProfPresent = 0;
static int sProfN = 0;
#endif

static void gfx_citro3d_start_frame(void) {
#if PD_DEBUG3DS
    { u64 _t = svcGetSystemTick();
      if (sProfLastFinish) sProfGame += _t - sProfLastFinish;  // present→here = game sim + DL build
      sProfStart = _t; }
#endif
    sBakeFrame++;
    // Apply cache invalidations queued by the live PROP-facade registration (phase 5, draw_triangles).
    // Done HERE at the frame boundary — a safe point (no draw in flight) — never mid-record where
    // gfx_texture_cache_delete→gfx_flush would re-enter draw_triangles. The invalidated prop facade
    // re-decodes + bakes on this frame's first use, then stays baked (monotonic). §21.9.
    pdFacadeFlushInvalidations();
    // ★ Release baked textures deferred from the previous frame (its replay is done) — the
    // GPU free MUST happen here at the frame boundary, never mid-record (dropReg defers here).
    // FUNCTIONAL (not debug): always runs.
    for (int i = 0; i < sBakePendingCount; i++) {
        int slot = sBakePendingFree[i];
        if (slot > 0 && slot < TEX_POOL_SIZE && sTexValid[slot]) { C3D_TexDelete(&sTexPool[slot]); sTexValid[slot] = false; }
        bakeReturnSlot(slot);
    }
    sBakePendingCount = 0;
#if PD_DEBUG3DS
    // Frame-loop heartbeat (DEBUG ONLY — writes the SD card ~1x/sec): render loop alive +
    // draw volume + bake counters + MVP mode/tier. Gated off for production (PD_DEBUG3DS=0).
    // Sticky worst-case across ALL frames: true peak VBO usage + min free linear heap.
    static uint32_t sVboPeak = 0; static uint32_t sLinFreeMinKB = 0xFFFFFFFFu;
    if (sVboIdx > sVboPeak) sVboPeak = sVboIdx;
    { uint32_t fkb = (uint32_t)(linearSpaceFree() >> 10); if (fkb < sLinFreeMinKB) sLinFreeMinKB = fkb; }
    if ((sFrameCounter % 60) == 0) {
        (void)gfxIsNew3ds();   // probe tier once for the self-verifying n3ds= log
        char b[256];
        // t=<ms> lets fps be computed from boot.log on REAL HARDWARE: fps ≈ 60000/Δt.
        // n3ds records the active tier; bake=/skip= track the facade bake.
        snprintf(b, sizeof(b), "frame %d: t=%llums cmds=%d verts=%lu vpeak=%u/%u overflow=%d freeMinKB=%u bake=%d/%d skip=%d n3ds=%d",
                 sFrameCounter, (unsigned long long)osGetTime(), sCmdCount, (unsigned long)sVboIdx,
                 (unsigned)sVboPeak, (unsigned)VBO_MAX_VERTS, (int)sVboOverflow, sLinFreeMinKB,
                 sBakeActive, BAKE_CAP, sBakeSkip, sIsNew3ds);
        plat3dsBootLog(b);
        { char bl[128];   // BLUR chain diag: capReq=post-frame copies, sample=blur FB binds, blit=0/1/2 (none/black/real)
          snprintf(bl, sizeof(bl), "BLUR fbe=%d capReq=%d sample=%d blit=%d prevRT=%d gameValid=%d",
                   (int)gfx_framebuffers_enabled, sBlurCapReq, sBlurSample, sBlurBlit,
                   (int)(sPrevSceneRT != NULL), (int)sGameFbValid);
          plat3dsBootLog(bl); sBlurCapReq = 0; sBlurSample = 0; }
        { char bk[96]; snprintf(bk, sizeof(bk), "FBBIND leak=%d total=%d leakTexAddr=%p leakNV=%u", sFbBindLeak, sFbBindTotal, (void*)sFbBindLeakAddr, (unsigned)sFbBindLeakNV);
          plat3dsBootLog(bk); sFbBindLeak = 0; sFbBindTotal = 0; }
        if (sProfN > 0) {  // PERF PROFILE: avg µs/frame per macro-phase (ticks→µs). present≈0 ⇒ CPU-bound.
            u64 us = (u64)(SYSCLOCK_ARM11 / 1000000); if (!us) us = 1;
            char pb[128];
            snprintf(pb, sizeof(pb), "PROF game=%luus interp=%luus replay=%luus present=%luus n=%d",
                     (unsigned long)(sProfGame / sProfN / us), (unsigned long)(sProfInterp / sProfN / us),
                     (unsigned long)(sProfReplay / sProfN / us), (unsigned long)(sProfPresent / sProfN / us), sProfN);
            plat3dsBootLog(pb);
            sProfGame = sProfInterp = sProfReplay = sProfPresent = 0; sProfN = 0;
        }
        FILE *ab = fopen("sdmc:/3ds/perfectdark/autobake.txt", "r"); // A/B toggle: bake on/off
        if (ab) { int v; if (fscanf(ab, "%d", &v) == 1) sAutoBake = (v != 0); fclose(ab); }
        FILE *bt = fopen("sdmc:/3ds/perfectdark/baketarget.txt", "r"); // live bake-size A/B (64..512), next bake
        if (bt) { int v; if (fscanf(bt, "%d", &v) == 1 && v >= 64 && v <= 512) sBakeTarget = (uint32_t)v; fclose(bt); }
        FILE *bs = fopen("sdmc:/3ds/perfectdark/bakespan.txt", "r"); // live tiling-threshold A/B (×10, e.g. 30=3.0)
        if (bs) { int v; if (fscanf(bs, "%d", &v) == 1 && v >= 15 && v <= 120) sBakeSpanMin = (float)v * 0.1f; fclose(bs); }
        FILE *mg = fopen("sdmc:/3ds/perfectdark/magenta.txt", "r"); // DIAG: tint a texture addr magenta
        if (mg) { unsigned long v; if (fscanf(mg, "%lx", &v) == 1) sMagentaAddr = (uintptr_t)v; else sMagentaAddr = 0; fclose(mg); } else sMagentaAddr = 0;
        FILE *tl = fopen("sdmc:/3ds/perfectdark/texlodmips.txt", "r"); // §21.11 A/B: honor tex_lod → mips
        if (tl) { int v; if (fscanf(tl, "%d", &v) == 1) sTexLodMips = (v != 0); fclose(tl); }
        FILE *mn = fopen("sdmc:/3ds/perfectdark/mipnearest.txt", "r"); // mip filter: 1=nearest 0=linear
        if (mn) { int v; if (fscanf(mn, "%d", &v) == 1) sMipNearest = (v != 0); fclose(mn); }
        FILE *fge = fopen("sdmc:/3ds/perfectdark/fog.txt", "r");       // live fog master A/B (1=on 0=off)
        if (fge) { int v; if (fscanf(fge, "%d", &v) == 1) sFogEnable = (v != 0); fclose(fge); }
        FILE *fzf = fopen("sdmc:/3ds/perfectdark/fogzflip.txt", "r");  // DEV: fog depth-index direction A/B
        if (fzf) { int v; if (fscanf(fzf, "%d", &v) == 1) sFogZFlip = (v != 0); fclose(fzf); }
        FILE *ftf = fopen("sdmc:/3ds/perfectdark/fbtest.txt", "r"); // §7.1.1 #4: RT-from-tex round-trip A/B
        if (ftf) { int v; if (fscanf(ftf, "%d", &v) == 1) sFbTest = (v != 0); fclose(ftf); }
        FILE *fuv = fopen("sdmc:/3ds/perfectdark/fbuv.txt", "r"); // live blit-UV calibration: s0 s1 t0 t1
        if (fuv) { float a,b,c,e; if (fscanf(fuv, "%f %f %f %f", &a,&b,&c,&e) == 4) { sUvS0=a; sUvS1=b; sUvT0=c; sUvT1=e; } fclose(fuv); }
        FILE *fsn = fopen("sdmc:/3ds/perfectdark/fbsnap.txt", "r"); // live snapshot calibration: orient u0 u1 v0 v1
        if (fsn) { int o; float a,b,c,e; if (fscanf(fsn, "%d %f %f %f %f", &o,&a,&b,&c,&e) == 5) { sSnapOrient=o&7; sSnapU0=a; sSnapU1=b; sSnapV0=c; sSnapV1=e; } fclose(fsn); }
        { char mb[96]; snprintf(mb, sizeof(mb), "TEXLODMIP on=%d nearest=%d mipped=%d ~KB=%u",
            sTexLodMips, sMipNearest, sTexMipCount, (unsigned)(sTexMipBytes >> 10)); plat3dsBootLog(mb); }
    }
#endif
    // ── Lightweight PRODUCTION memory log (memlog.txt=1) — the diagnostic for the intermittent "wrong mip
    //    level" blur (§23 FCRAM). Tracks free linear heap + OOM/bake-skip counts, ~1×/sec, no per-draw cost.
#ifdef BK_TRACE
    if (!sMemLog) sMemLog = true; /* BK: production mem/bake heartbeat always on in TRACE builds
                                    * (device-side bake-engagement evidence for the texture fix) */
#endif
    if (sMemLog) {
        uint32_t fkb = (uint32_t)(linearSpaceFree() >> 10);
        if (fkb < sMemFreeMinKB) sMemFreeMinKB = fkb;
        if ((sFrameCounter % 60) == 0) {
            char mb[224];
            // ★ Memory-region readout: how much TOTAL app FCRAM is unallocated (can grow the linear/GPU heap
            // into it) + the system region. appFree = headroom to expand the bake budget. linFree = the GPU
            // heap (the bake/texture pool) — the thing that hit 2.6MB.
            uint32_t appFreeKB = (uint32_t)(osGetMemRegionFree(MEMREGION_APPLICATION) >> 10);
            uint32_t appUsedKB = (uint32_t)(osGetMemRegionUsed(MEMREGION_APPLICATION) >> 10);
            uint32_t sysFreeKB = (uint32_t)(osGetMemRegionFree(MEMREGION_SYSTEM) >> 10);
            /* ★ VRAM free (6MB pool — render targets + framebuffer-effect textures live here, NOT in the
             * linear/FCRAM heap the rest of this line tracks). The Lost City hard freeze is GPU-side,
             * system-wide (kills the audio-thread watchdog), and NOT FCRAM (linFree stable, texOOM=0) — a slow
             * VRAM leak over a long session would be invisible to everything else here and hard-wedge the GPU
             * when exhausted. If vramFreeKB declines toward 0 over the session, that's the freeze. */
            uint32_t vramFreeKB = (uint32_t)(vramSpaceFree() >> 10);
            if (vramFreeKB < sVramFreeMinKB) sVramFreeMinKB = vramFreeKB;
            snprintf(mb, sizeof(mb), "MEM frame=%d mips=%d linFreeKB=%u linMinKB=%u vramFreeKB=%u vramMinKB=%u appFreeKB=%u appUsedKB=%u sysFreeKB=%u texOOM=%u bake=%d/%d bakeKB=%u/%u bakeSkip=%d",
                     sFrameCounter, (int)sMipsEnabled, fkb, sMemFreeMinKB, vramFreeKB, sVramFreeMinKB, appFreeKB, appUsedKB, sysFreeKB, sTexOomCount,
                     sBakeActive, BAKE_CAP, (unsigned)(sBakeBytes >> 10), (unsigned)(BAKE_MEM_BUDGET >> 10),
                     sBakeSkip);
            plat3dsBootLog(mb);
        }
    }
    sFrameCounter++;

    if (!sInFrame) {
        C3D_FrameBegin(C3D_FRAME_SYNCDRAW);
        sInFrame = true;
        BK_TR(BK_TR_C3D, "C3D_FrameBegin (opened C3D frame)");
    }
#ifdef BK_TRACE
    /* Pixel dumps of presented frames — gives the autonomous loop EYES without a
     * human at the screen. Two phases per dump, NO blocking waits (a wedged wait
     * would stall the auto-quit/chainload like a crash):
     *   frame N+1 begin: C3D_FrameBegin(SYNCDRAW) just idled the GPU and the
     *     colorBuf still holds frame N (its clear only happens in end_frame),
     *     so queue a GX_DisplayTransfer untile VRAM->linear. GPU DMA only — the
     *     CPU NEVER dereferences VRAM (the data-abort lesson).
     *   next begin: that transfer was serialized before frame N+1's work, which
     *     SYNCDRAW has now fully drained -> the linear copy is complete;
     *     invalidate CPU cache and write it to SD as fb<N>.raw.
     * Host: 240x400 RGBA8, row-major 240-wide (portrait) -> rotate to 400x240. */
    {
        static u32 *sBkFbDump = NULL;
        static int  sBkFbDumpFrame = 0;
        static const int sBkFbWant[] = { 121, 401, 621, 911, 1201, 2401 }; /* intro sweep + TRANSITION frames (snap fired f602/f880) + file select */
        if (sBkFbDump) {
            GSPGPU_InvalidateDataCache(sBkFbDump, 240 * 400 * 4);
            char fbp[64];
            snprintf(fbp, sizeof(fbp), "sdmc:/3ds/banjo/fb%d.raw", sBkFbDumpFrame);
            FILE *ff = fopen(fbp, "wb");
            if (ff) {
                fwrite(sBkFbDump, 1, 240 * 400 * 4, ff);
                fclose(ff);
            }
            linearFree(sBkFbDump);
            sBkFbDump = NULL;
            BK_TR(BK_TR_PRESENT, "fb%d.raw written (240x400 RGBA8 linear)", sBkFbDumpFrame);
        }
        for (size_t wi = 0; wi < sizeof(sBkFbWant) / sizeof(sBkFbWant[0]); wi++) {
            if (bkTraceFrame != sBkFbWant[wi]) continue;
            C3D_RenderTarget *t = (C3D_RenderTarget *)gfx3dsTopTarget(0);
            if (t && t->frameBuf.colorBuf) {
                sBkFbDump = (u32 *)linearAlloc(240 * 400 * 4);
                if (sBkFbDump) {
                    sBkFbDumpFrame = bkTraceFrame - 1;
                    GX_DisplayTransfer((u32 *)t->frameBuf.colorBuf, GX_BUFFER_DIM(240, 400),
                                       sBkFbDump, GX_BUFFER_DIM(240, 400),
                                       GX_TRANSFER_IN_FORMAT(GX_TRANSFER_FMT_RGBA8) |
                                       GX_TRANSFER_OUT_FORMAT(GX_TRANSFER_FMT_RGBA8) |
                                       GX_TRANSFER_OUT_TILED(0) | GX_TRANSFER_FLIP_VERT(0) |
                                       GX_TRANSFER_RAW_COPY(0) |
                                       GX_TRANSFER_SCALING(GX_TRANSFER_SCALE_NO));
                    BK_TR(BK_TR_PRESENT, "fb%d transfer queued (colorBuf->linear)", sBkFbDumpFrame);
                }
            }
            break;
        }
    }
#endif
    sVboIdx = 0;
    sCmdCount = 0;
    sVboOverflow = false;
    sBakeThisFrame = 0; // reset per-frame new-bake budget (BAKE_PERFRAME)
    memset(sFbCopiedInStream, 0, sizeof(sFbCopiedInStream)); // cheap; unconditional so toggling effects OFF
    sFbSampleThisFrame = false;                              // mid-session can't leave a stale-armed indirect
    sPendingFbBind = NULL;   // ★ start each frame with NO pending FB bind — else the prior frame's blur/lens
                             // bind LEAKS into this frame's first draws (e.g. the lens-flare glare), which then
                             // get the orient remap + sample the scene snapshot = broken/un-mirrored flares.
    setupPipeline();
    // §7.1 motion/zoom blur: the cross-frame snapshot is captured SAME-FRAME inside renderEyeIndirect (after
    // the scene renders to sGameFbRT, via the FrameDrawOn switch that makes sGameFbTex sample-coherent) — NOT
    // here at start_frame. Reading sGameFbTex (an RT's backing tex) cross-frame, before any FrameDrawOn switch
    // this frame, returns STALE/BLACK (the PICA has no RT→texture coherency without a switch; proven by a
    // red-clear A/B: the blur sampled red fine but a cross-frame fbBlit of sGameFbTex landed black). See §7.1.2.
}

// §7.1 3b — render one eye WITH the framebuffer effect via a pure FORWARD chain of C3D_FrameDrawOn
// switches (no FrameSplit, never returning to a prior target — the only reliable mid-frame pattern on C3D;
// the old "snapshot then return to sGameFbRT" round-trip corrupted sGameFbTex → the static twitch, and even
// a forward-chain SNAPSHOT landed stale under motion → the yaw twitch). FIX A chain: sGameFbRT (pre-lens
// scene) → eye (base scene blit + the lens, which samples sGameFbTex DIRECTLY with a per-vertex UV remap).
// Each FrameDrawOn flushes the prior target, so the sample is "after one switch" = the stable 3a pattern.
// copyIdx<0 ⇒ no effect this frame ⇒ degenerates to the plain 3a path (scene → sGameFbRT → eye blit).
static void renderEyeIndirect(C3D_RenderTarget *eye, const C3D_Mtx *tf, int copyIdx, bool capture) {
    // FIX A (no snapshot): only TWO targets, ONE forward switch. The lens samples sGameFbTex DIRECTLY
    // (the already-stable eye-blit read — no snapshot tex to land stale under motion → no twitch). The
    // rotation/un-pad is applied as a per-vertex UV remap on the lens verts (draw_triangles, sSnapOrient +
    // sub-rect) instead of an un-rotating render pass.
    C3D_RenderTargetClear(sGameFbRT, C3D_CLEAR_ALL, 0x000000FF, 0xFFFFFFFF);
    C3D_FrameDrawOn(sGameFbRT);
    replayRange(tf, 0, copyIdx < 0 ? sCmdCount : copyIdx);     // scene up to the lens → sGameFbRT
    sGameFbValid = true;                                       // sGameFbTex holds a real scene (heartbeat diag)
    // §7.1 motion/zoom blur — SAME-FRAME snapshot for the NEXT frame's blur. The FrameDrawOn(sPrevSceneRT)
    // switch flushes sGameFbRT → sGameFbTex sample-coherent (exactly like the eye blit below, which works),
    // so the fbBlit reads the JUST-rendered scene (not the stale cross-frame black). Forward chain
    // sGameFbRT → sPrevSceneRT → eye (no FrameSplit, no return). The blur quad in THIS frame already sampled
    // the PRIOR snapshot during the scene replay above (read-before-write) → cross-frame preserved.
    if (capture && prevSceneEnsure()) {
        C3D_FrameDrawOn(sPrevSceneRT);
        // ★ Copy the SCENE REGION [0,TOP_W/256]×[0,TOP_H/512] of sGameFbTex into the SAME [0,TOP_W]×[0,TOP_H]
        // sub-rect of sPrevSceneRT using the VALIDATED (TOP_W,TOP_H) viewport — i.e. a 1:1 scene-region copy
        // (240×400 → 240×400, NO scale, so it still CONVERGES at rest; the §7.1.2 "X" bug was a 256→240 SCALE,
        // which this avoids). The blur then samples sPrevSceneTex at the SAME [0,TOP_W/256]×[0,TOP_H/512] region
        // it already used → pixel-aligned. ★ REAL-HW FIX: the previous `C3D_SetViewport(0,0,256,512)` (a size
        // used NOWHERE else) shifted the capture ~20% on the PICA (512 vs the 400 panel) → the blur drew offset
        // with black at the top-left; the scene render + eye blit + lens all use (TOP_W,TOP_H)=(240,400) and are
        // HW-validated, so the capture must use it too. (Mandarine filled either viewport, masking this.)
        fbBlit(&sGameFbTex, 0, 0.f, (float)TOP_W / 256.f, 0.f, (float)TOP_H / 512.f, TOP_W, TOP_H);
#if PD_DEBUG3DS
        sBlurBlit = 2;
#endif
    }
    C3D_RenderTargetClear(eye, C3D_CLEAR_ALL, 0x000000FF, 0xFFFFFFFF);
    C3D_FrameDrawOn(eye);                                      // forward switch (flushes the prior target → coherent)
    fbBlit(&sGameFbTex, 0, sUvS0, sUvS1, sUvT0, sUvT1, TOP_W, TOP_H);  // base scene → eye (the lens covers it where opaque)
    if (copyIdx >= 0)
        replayRange(tf, copyIdx + 1, sCmdCount);              // lens + HUD → eye; the lens samples sGameFbTex
}

static void gfx_citro3d_end_frame(void) {
    g_turok_phase = "gpu_replayL";                    /* watchdog: submitting the left/main eye's draws */
#if PD_DEBUG3DS
    sProfEFStart = svcGetSystemTick();
    if (sProfStart) sProfInterp += sProfEFStart - sProfStart;  // start_frame→here = gfx_run_dl (gfx_pc)
#endif
    // Replay the recorded command list once per eye. Geometry uploaded once;
    // only the transform uniform changes between eyes → single-pass stereo.
    C3D_Mtx tf;
    float level = gfx3dsStereoLevel();
    bool stereo = gfx3dsStereoActive() && level > 0.0f;
    buildTransform(&sMonoTf, 0.f, level, 1.0f);   // ★ no-shear transform for the HUD-flatten (eyeSign=0); HUD never warp-zooms

    // Single-pass stereo: the geometry VBO is uploaded once; only the per-eye `transform`
    // changes. replayCommands folds it into each draw's full MVP (× MP_full for GPU-MVP
    // draws) on the CPU and uploads ONE matrix/draw (deduped) — 1 mul/vertex on the GPU.
    // §7.1.1: a framebuffer EFFECT (copy_framebuffer, fbOp==1) routes the scene through the RT-from-tex
    // game-framebuffer so the effect can sample it, then the eye gets the scene + the lens (renderEye
    // Indirect). ★ We do this ONLY on frames that actually contain an effect — `gfx_framebuffers_enabled`
    // can be ON for a whole level while the scope/eyespy is used only occasionally, and paying the
    // offscreen render + blit every frame is wasteful. No effect this frame ⇒ direct-to-eye (the stable
    // 3a path; byte-identical to effects-off). copy_framebuffer only records fbOp when fb effects are on,
    // so copyIdx>=0 already implies enabled; sFbTest is the dev round-trip harness.
    C3D_RenderTarget *left = (C3D_RenderTarget *)gfx3dsTopTarget(0);
    int copyIdx = -1;
    if (gfx_framebuffers_enabled || sFbTest)
        for (int i = 0; i < sCmdCount; i++) if (sCmds[i].fbOp == 1) { copyIdx = i; break; }
    // The blur SAMPLES a cross-frame snapshot (sFbSampleThisFrame) but has NO in-stream copy (copyIdx stays
    // -1; its capture is post-frame). It still needs the indirect render so sGameFbTex holds THIS frame's
    // scene for the next start_frame's deferred capture. copyIdx<0 ⇒ renderEyeIndirect degenerates to the
    // plain 3a path (whole scene → sGameFbRT → eye), which is exactly what the blur wants.
    bool useIndirect = (copyIdx >= 0 || sFbSampleThisFrame || sFbTest) && fbTestEnsure();
    // Capture THIS frame's scene into sPrevSceneTex (for the NEXT frame's blur) once, on the LEFT eye —
    // a post-frame copy_framebuffer requested it (sPrevSceneCapPending). Mono snapshot (both eyes' blur
    // sample it next frame). Consume the request whether or not the indirect runs this frame.
    bool doCapture = sPrevSceneCapPending && useIndirect;
    if (doCapture) sPrevSceneCapPending = false;   // consume only when we actually capture (else keep for next indirect frame)

    // Left / main eye
    buildTransform(&tf, stereo ? -1.f : 0.f, level, g_turok_warp_zoom);
#ifdef BK_TRACE
    /* Present-path discriminator (trace builds only): clear MAGENTA instead of
     * black. Screen shows magenta -> target->transfer->display works and the
     * black-screen bug is draw-level (TEV). Screen stays black -> either a
     * screen-filling draw covers the clear (check the d# NDC bboxes) or the
     * present chain itself is broken. */
#define BK_CLEAR_COLOR 0xFF00FFFF
#else
#define BK_CLEAR_COLOR 0x000000FF
#endif
    if (useIndirect) {
        renderEyeIndirect(left, &tf, copyIdx, doCapture);
    } else {
        C3D_RenderTargetClear(left, C3D_CLEAR_ALL, BK_CLEAR_COLOR, 0xFFFFFFFF);
        C3D_FrameDrawOn(left);
        replayRange(&tf, 0, sCmdCount);
    }

    if (stereo) {
        g_turok_phase = "gpu_replayR";                /* watchdog: submitting the RIGHT eye (stereo doubles GPU load) */
        C3D_RenderTarget *right = (C3D_RenderTarget *)gfx3dsTopTarget(1);
        if (right) {
            buildTransform(&tf, 1.f, level, g_turok_warp_zoom);
            if (useIndirect) {
                renderEyeIndirect(right, &tf, copyIdx, false);   // re-renders the shared sGameFbTex per eye (no re-capture)
            } else {
                C3D_RenderTargetClear(right, C3D_CLEAR_ALL, 0x000000FF, 0xFFFFFFFF);
                C3D_FrameDrawOn(right);
                replayRange(&tf, 0, sCmdCount);
            }
        }
    }

    // Bottom screen unused by PD's top-screen HUD layout — keep it cleared.
    C3D_RenderTarget *bottom = (C3D_RenderTarget *)gfx3dsBottomTarget();
    if (bottom) {
        C3D_RenderTargetClear(bottom, C3D_CLEAR_ALL, 0x000000FF, 0xFFFFFFFF);
        C3D_FrameDrawOn(bottom);
    }
#if PD_DEBUG3DS
    sProfReplay += svcGetSystemTick() - sProfEFStart;          // the per-eye replay (C3D submit)
#endif
}

static void gfx_citro3d_finish_render(void) {
    BK_TR(BK_TR_PRESENT, "finish_render %s drawCmds=%d verts=%d overflow=%d",
          sInFrame ? "PRESENTED" : "SKIPPED (stale VRAM!)",
          sCmdCount, sVboIdx, (int)sVboOverflow);
    if (sInFrame) {
        g_turok_phase = "gpu_frameend";                  /* watchdog: BLOCKED in C3D_FrameEnd = GPU sync/present wedge */
#if PD_DEBUG3DS
        u64 _p = svcGetSystemTick();
#endif
        C3D_FrameEnd(0);
        g_turok_phase = "gpu_done";
        sInFrame = false;
#if PD_DEBUG3DS
        { u64 _t = svcGetSystemTick(); sProfPresent += _t - _p; sProfLastFinish = _t; sProfN++; }
#endif
    }
}

