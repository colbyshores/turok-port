static const int sTileOrder[16] = { 0,1,4,5, 2,3,6,7, 8,9,12,13, 10,11,14,15 };

static inline uint32_t rgba_to_abgr(uint32_t c) {
    return ((c & 0xFF) << 24) | (((c >> 8) & 0xFF) << 16) |
           (((c >> 16) & 0xFF) << 8) | (c >> 24);
}

// Pack a source RGBA8 texel (byte order R,G,B,A) into a PICA GPU_RGBA4 u16:
// R[15:12] G[11:8] B[7:4] A[3:0]. Half the FCRAM of GPU_RGBA8 at 16-bit colour.
// ★ Used ONLY for BAKED (pre-tiled building) textures — global RGBA4 visibly bands
// the normal level textures, but on the repeating window-grid bakes it's invisible
// and halves the bake footprint. Renderer-level + format-agnostic tiling → reusable.
static inline uint16_t rgba_to_rgba4(uint32_t c) {
    uint32_t r = (c & 0xFF) >> 4;
    uint32_t g = ((c >> 8) & 0xFF) >> 4;
    uint32_t b = ((c >> 16) & 0xFF) >> 4;
    uint32_t a = ((c >> 24) & 0xFF) >> 4;
    return (uint16_t)((r << 12) | (g << 8) | (b << 4) | a);
}
// Pack source RGBA8 (R,G,B,A) into PICA GPU_RGB565 u16: R[15:11] G[10:5] B[4:0]. Same 16-bit
// size as RGBA4 but NO alpha → 5/6/5 colour bits (vs 4/4/4) = less banding. Used for OPAQUE
// baked facades (the window grids); textures with real alpha keep RGBA4.
static inline uint16_t rgba_to_rgb565(uint32_t c) {
    uint32_t r = (c & 0xFF) >> 3;
    uint32_t g = ((c >> 8) & 0xFF) >> 2;
    uint32_t b = ((c >> 16) & 0xFF) >> 3;
    return (uint16_t)((r << 11) | (g << 5) | b);
}

static void swizzleTexture(const uint8_t *src, uint32_t *dst, uint32_t w, uint32_t h) {
    const uint32_t *s = (const uint32_t *)src;
    uint32_t offs = 0;
    for (uint32_t y = 0; y < h; y += 8) {
        for (uint32_t x = 0; x < w; x += 8) {
            for (int i = 0; i < 64; i++) {
                int x2 = i & 7, y2 = i >> 3;
                int pos = sTileOrder[(x2 & 3) + ((y2 & 3) << 2)] + ((x2 >> 2) << 4) + ((y2 >> 2) << 5);
                dst[offs + pos] = rgba_to_abgr(s[(y + y2) * w + x + x2]);
            }
            offs += 64;
        }
    }
}

static uint32_t nextPOT(uint32_t v) {
    if (v < 8) return 8;
    if ((v & (v - 1)) == 0) return v;
    return 1u << (32 - __builtin_clz(v - 1));
}

static uint32_t gfx_citro3d_new_texture(void) {
    uint32_t id;
    if (sTexFreeCount > 0) {
        id = sTexFree[--sTexFreeCount];
    } else if (sTexNext < TEX_POOL_USABLE) {   // stop BELOW the reserved bake range
        id = sTexNext++;
    } else {
        id = 1; // pool exhausted: alias slot 1 (degrades gracefully)
    }
    sTexValid[id] = false;
    sTexScaleS[id] = 1.f; sTexScaleT[id] = 1.f;
    // Free only this slot's kept SOURCE (the registry bake is content-keyed and persists).
    if (sBakeSrc[id]) { free(sBakeSrc[id]); sBakeSrc[id] = NULL; sBakeSrcW[id] = 0; sBakeSrcH[id] = 0; }
    sBakeHash[id] = 0;
    return id;
}

static void gfx_citro3d_delete_texture(uint32_t id) {
    if (id == 0 || id >= TEX_POOL_SIZE) return;
    if (sBakeSrc[id]) { free(sBakeSrc[id]); sBakeSrc[id] = NULL; sBakeSrcW[id] = 0; sBakeSrcH[id] = 0; }
    sBakeHash[id] = 0;
    if (sTexValid[id]) {
        C3D_TexDelete(&sTexPool[id]);
        sTexValid[id] = false;
    }
    if (sTexFreeCount < TEX_POOL_SIZE) sTexFree[sTexFreeCount++] = id;
}

static void gfx_citro3d_select_texture(int tile, uint32_t id, bool linear) {
    stTexUnit[tile] = (int16_t)id;
    stTexLinear[tile] = linear;
    sCurTexId = id;
    if (tile == 0) sPendingFbBind = NULL;   // a normal texture select cancels a pending FB bind (§7.1 3b)
}

// 8x8 Morton tile a linear RGBA8 (u32) buffer into a 16-bit (u16) destination — RGB565 when
// `rgb565` (opaque facades, better colour), else RGBA4 (carries the source's alpha).
static void swizzleTex16(const uint32_t *lin, uint16_t *dst, uint32_t w, uint32_t h, bool rgb565) {
    uint32_t offs = 0;
    for (uint32_t y = 0; y < h; y += 8)
        for (uint32_t x = 0; x < w; x += 8) {
            for (int i = 0; i < 64; i++) {
                int x2 = i & 7, y2 = i >> 3;
                int pos = sTileOrder[(x2 & 3) + ((y2 & 3) << 2)] + ((x2 >> 2) << 4) + ((y2 >> 2) << 5);
                uint32_t c = lin[(y + y2) * w + x + x2];
                dst[offs + pos] = rgb565 ? rgba_to_rgb565(c) : rgba_to_rgba4(c);
            }
            offs += 64;
        }
}

// ── OG-3DS lomem: repack an already-tiled PICA RGBA8 word (R<<24|G<<16|B<<8|A, the layout rgba_to_abgr
//    writes) to 16-bit IN PLACE in sTexScratch. The 8x8 Morton tile order is identical for RGBA8/RGB565/
//    RGBA4, so a per-texel repack at the same linear index needs no re-swizzle; u16[i] (byte 2i) never
//    overruns the u32[i] (byte 4i) we read, so the forward in-place pass is safe. Halves texture FCRAM.
static inline uint16_t pica8_to_rgb565(uint32_t v) {
    uint32_t r=(v>>24)&0xFF, g=(v>>16)&0xFF, b=(v>>8)&0xFF;
    return (uint16_t)(((r>>3)<<11) | ((g>>2)<<5) | (b>>3));
}
static inline uint16_t pica8_to_rgba4(uint32_t v) {
    uint32_t r=(v>>24)&0xFF, g=(v>>16)&0xFF, b=(v>>8)&0xFF, a=v&0xFF;
    return (uint16_t)(((r>>4)<<12) | ((g>>4)<<8) | ((b>>4)<<4) | (a>>4));
}
static inline void scratchToLo16(uint32_t texels, bool opaque) {
    uint16_t *d = (uint16_t *)sTexScratch; const uint32_t *s = sTexScratch;
    if (opaque) for (uint32_t i = 0; i < texels; i++) d[i] = pica8_to_rgb565(s[i]);
    else        for (uint32_t i = 0; i < texels; i++) d[i] = pica8_to_rgba4(s[i]);
}

// ── bake: dedicated slot pool over [TEX_POOL_USABLE, TEX_POOL_SIZE) ──
static int bakeAllocSlot(void) {
    if (!sBakeFreeInit) {
        for (int i = 0; i < BAKE_RESERVE; i++) sBakeFree[i] = TEX_POOL_USABLE + i;
        sBakeFreeCount = BAKE_RESERVE; sBakeFreeInit = true;
    }
    if (sBakeFreeCount <= 0) return -1;
    return sBakeFree[--sBakeFreeCount];
}
static void bakeReturnSlot(int slot) {
    if (slot >= TEX_POOL_USABLE && slot < TEX_POOL_SIZE && sBakeFreeCount < BAKE_RESERVE)
        sBakeFree[sBakeFreeCount++] = slot;
}
// FNV-1a over the POT source texels — the content key. Stable for a given facade across
// re-imports (same ROM data → same decode → same hash). Never returns 0 (0 = empty entry).
static uint32_t bakeHash(const uint32_t *p, uint32_t n) {
    uint32_t h = 2166136261u;
    for (uint32_t i = 0; i < n; i++) { h ^= p[i]; h *= 16777619u; }
    return h ? h : 1u;
}
// Cross-thread acquire-load of a registry slot: the bake worker publishes sReg[].slot with a
// RELEASE store AFTER building the C3D_Tex, so an ACQUIRE load that sees slot >= 0 also sees the
// fully-built texture. Plain load when the worker is compiled out (PD_BAKE_THREAD=0).
#if PD_BAKE_THREAD
#define REG_SLOT(i) __atomic_load_n(&sReg[i].slot, __ATOMIC_ACQUIRE)
#else
#define REG_SLOT(i) (sReg[i].slot)
#endif
// Find a READY (published) registry bake by content (hash + dims guard). -1 = none.
static int regFind(uint32_t hash, uint16_t w, uint16_t h) {
    if (!hash) return -1;
    for (int i = 0; i < BAKE_CAP; i++)
        if (sReg[i].hash == hash && sReg[i].srcW == w && sReg[i].srcH == h && REG_SLOT(i) >= 0) return i;
    return -1;
}
// Find ANY entry for this content — ready OR still building (slot < 0). Async dedup so the same
// facade isn't queued twice while its bake is in flight.
static int regFindAny(uint32_t hash, uint16_t w, uint16_t h) {
    if (!hash) return -1;
    for (int i = 0; i < BAKE_CAP; i++)
        if (sReg[i].hash == hash && sReg[i].srcW == w && sReg[i].srcH == h) return i;
    return -1;
}
// Free a registry entry's bake (deferred slot free — never mid-record). Used only to reclaim
// a STALE cross-level entry when making room; current-level entries are never evicted.
static void dropReg(int ri) {
    if (ri < 0 || ri >= BAKE_CAP || sReg[ri].hash == 0) return;
    if (sReg[ri].slot >= 0 && sBakePendingCount < BAKE_RESERVE) sBakePendingFree[sBakePendingCount++] = sReg[ri].slot;
    if (sBakeBytes >= sReg[ri].bytes) sBakeBytes -= sReg[ri].bytes; else sBakeBytes = 0;
    if (sBakeActive > 0) sBakeActive--;
    sReg[ri].hash = 0; sReg[ri].slot = -1; sReg[ri].bytes = 0;
}
// Pick a registry index for a NEW bake: an empty slot, or evict the LRU entry IF it's STALE
// (unused for a while = a previous level's facade). If everything is recently-used (the
// current working set), return -1 → skip rather than evict a live bake (no thrash).
static int regAlloc(void) {
    for (int i = 0; i < BAKE_CAP; i++) if (sReg[i].hash == 0) return i;
    int lru = -1; uint32_t oldest = 0xFFFFFFFFu;
    for (int i = 0; i < BAKE_CAP; i++) if (sReg[i].lastUse < oldest) { oldest = sReg[i].lastUse; lru = i; }
    if (lru >= 0 && (sBakeFrame - oldest) > 180u) { dropReg(lru); return lru; } // stale ~3s+ → reclaim
    return -1;
}

static uintptr_t sPendingUploadAddr = 0;        // source addr of the in-flight upload (gfx_pc's orig_addr)
static uintptr_t sTexSrcAddr[TEX_POOL_SIZE];    // per-texid source addr — the seam for render-time facade
                                                // registration (draw_triangles → pdFacadeRegister) + diag.

// ── bakeBuildSlot: the actual bake — tile Nu×Nv into level-0, box-filter the mip chain, swizzle,
//    and C3D-upload into sTexPool[slot]. Parameterized on the scratch buffers (mip0/mip1 = bw*bh
//    RGBA8 each, swz = bw*bh u16) so it runs on EITHER the main thread (sync; main scratch) or the
//    bake worker (async; private worker scratch). ★ Touches ONLY linearAlloc/memcpy/C3D_TexLoadImage
//    (memcpy) and C3D_TexFlush (svcFlushProcessDataCache — a kernel syscall) — NEVER the C3D command
//    context — so it is safe to run off the render thread concurrently with rendering. ──
static uint32_t bakeBuildSlot(int slot, const uint32_t *src, uint32_t sw, uint32_t sh,
                              int Nu, int Nv, uint32_t bw, uint32_t bh,
                              uint32_t *mip0, uint32_t *mip1, uint16_t *swz) {
    for (uint32_t y = 0; y < bh; y++) {
        uint32_t sy = (uint32_t)(((uint64_t)y * (uint32_t)Nv * sh / bh) % sh);
        const uint32_t *srow = src + (size_t)sy * sw;
        uint32_t *drow = mip0 + (size_t)y * bw;
        for (uint32_t x = 0; x < bw; x++)
            drow[x] = srow[(uint32_t)(((uint64_t)x * (uint32_t)Nu * sw / bw) % sw)];
    }
    bool opaque = true;
    for (uint32_t i = 0, n = bw * bh; i < n; i++) if ((mip0[i] >> 24) != 0xFFu) { opaque = false; break; }
    const GPU_TEXCOLOR fmt = opaque ? GPU_RGB565 : GPU_RGBA4;
    if (sTexValid[slot]) C3D_TexDelete(&sTexPool[slot]);
    // ★ MIPS OFF (user directive): single-level bake = LOD-0 always (max detail at distance, shimmer OK).
    //   Also a smaller alloc (no mip chain → ~25% less FCRAM, eases the budget). The bake's UV
    //   normalization (residual [0,1]) still kills the f24 stripe; only the distance area-averaging is gone.
    if (!sMipsEnabled) {
        if (!C3D_TexInit(&sTexPool[slot], (u16)bw, (u16)bh, fmt)) return 0; // OOM → caller skips the bake
        swizzleTex16(mip0, swz, bw, bh, opaque);
        C3D_TexLoadImage(&sTexPool[slot], swz, GPU_TEXFACE_2D, 0);
        C3D_TexFlush(&sTexPool[slot]);
        sTexValid[slot] = true;
        C3D_TexSetFilter(&sTexPool[slot], GPU_LINEAR, GPU_LINEAR);
        C3D_TexSetWrap(&sTexPool[slot], GPU_REPEAT, GPU_REPEAT);
        sTexScaleS[slot] = 1.f; sTexScaleT[slot] = 1.f;
        sTexTilesS[slot] = false; sTexTilesT[slot] = false;
        return (uint32_t)((size_t)bw * bh * 2u);
    }
    const int maxLevel = C3D_TexCalcMaxLevel(bw, bh);
    // ★ GUARD the alloc (crash dump #81): under FCRAM pressure C3D_TexInitMipmap fails and returns a
    //   tex with NULL data; the old code then C3D_TexLoadImage'd into it → memcpy(NULL,…) data abort.
    if (!C3D_TexInitMipmap(&sTexPool[slot], (u16)bw, (u16)bh, fmt)) return 0; // OOM → caller skips the bake
    for (int L = 0; L <= maxLevel; L++) {
        const uint32_t lw = bw >> L, lh = bh >> L, box = 1u << L, nn = box * box;
        const uint32_t *lin = mip0;
        if (L > 0) {
            for (uint32_t y = 0; y < lh; y++)
                for (uint32_t x = 0; x < lw; x++) {
                    uint32_t ar = 0, ag = 0, ab = 0, aa = 0;
                    for (uint32_t by = 0; by < box; by++)
                        for (uint32_t bx = 0; bx < box; bx++) {
                            uint32_t c = mip0[(y * box + by) * bw + (x * box + bx)];
                            ar += c & 0xff; ag += (c >> 8) & 0xff; ab += (c >> 16) & 0xff; aa += (c >> 24) & 0xff;
                        }
                    mip1[y * lw + x] = (ar / nn) | ((ag / nn) << 8) | ((ab / nn) << 16) | ((aa / nn) << 24);
                }
            lin = mip1;
        }
        swizzleTex16(lin, swz, lw, lh, opaque);
        C3D_TexLoadImage(&sTexPool[slot], swz, GPU_TEXFACE_2D, L);
    }
    C3D_TexFlush(&sTexPool[slot]);
    sTexValid[slot] = true;
    C3D_TexSetFilter(&sTexPool[slot], GPU_LINEAR, GPU_LINEAR);
    C3D_TexSetFilterMipmap(&sTexPool[slot], GPU_LINEAR);
    C3D_TexSetWrap(&sTexPool[slot], GPU_REPEAT, GPU_REPEAT);
    sTexScaleS[slot] = 1.f; sTexScaleT[slot] = 1.f;
    sTexTilesS[slot] = false; sTexTilesT[slot] = false;
    return (uint32_t)((size_t)bw * bh * 2u);
}

#if PD_BAKE_THREAD
// ── ASYNC FACADE BAKE WORKER (CLAUDE.md §23) ────────────────────────────────────────────────────
// Each bake is ~1-2 ms on the ARM11; a room's ~25-facade burst at load = a stop-the-world freeze.
// This runs the build on a LOW-priority worker (N3DS spare core 2 / OG system core 1). The main
// thread only RESERVES a slot+registry entry, copies the small POT source, and queues a job; the
// facade draws RAW (striped) for the few frames until the worker publishes its bake, then swaps in.
// Hot path is LOCK-FREE: regFind acquire-loads the worker's release-published slot; only the small
// job ring takes sBakeLock. Gated by PD_BAKE_THREAD (build) + bakethread.txt (runtime).
#define BAKEQ_MAX 32          // bounds in-flight QUEUED source copies (≤32×~64KB ≈ 2 MB) on the tight
                              // FCRAM heap — an unbounded queue (256) let a pre-warm burst pile up MBs
                              // of copies → OOM → the C3D_TexInitMipmap NULL-tex crash (dump #81).
                              // Overflow falls through to a SYNCHRONOUS build (bounded, no pile-up).
#define BAKE_THREAD_DIM 256   // worker scratch sized for a 256² bake; the async path clamps tgt to this
// Only the heavily-TILED towers (Nu or Nv > 2) go to the worker — their room-load burst is the
// stop-the-world freeze. The §21.10 minified point-facade (`0xae93464`) is registered at exactly
// 2×2, so it (and any ≤2×2 bake) builds SYNC even when threaded: it's rare ("self-narrowing, one
// per 360°"), cheap (~one bake), and MUST be guaranteed + immediate — the proven §21.10 path.
// Threading it changed its late/render-time timing + budget race and dropped that facade's bake.
// Tiling (not pixel size) is the discriminator: tiled facades are always Nu≥4 (span>3), so this
// threads every tower regardless of its source size and syncs only the 2×2 minified class.
typedef struct { uint32_t *src; uint16_t sw, sh; uint8_t Nu, Nv; uint16_t bw, bh; int slot; int ri; } BakeJob;
static BakeJob    sBakeQ[BAKEQ_MAX];
static int        sBakeQHead = 0, sBakeQTail = 0;     // ring; head==tail → empty
static LightLock  sBakeQLock;                         // guards ONLY the job ring (not the heavy build)
static LightEvent sBakeWake;
static Thread     sBakeWorker = NULL;
static volatile bool sBakeQuit = false;
static bool       sBakeThreadOn = false;              // armed at start (bakethread.txt)
static uint32_t  *sWMip0 = NULL, *sWMip1 = NULL;      // private worker scratch (256² RGBA8)
static uint16_t  *sWSwz  = NULL;                       // private worker swizzle scratch (256² u16)

static void bakeWorkerMain(void *arg) {
    (void)arg;
    while (!sBakeQuit) {
        LightEvent_Wait(&sBakeWake);
        for (;;) {
            BakeJob job; bool have = false;
            LightLock_Lock(&sBakeQLock);
            if (sBakeQHead != sBakeQTail) { job = sBakeQ[sBakeQHead]; sBakeQHead = (sBakeQHead + 1) % BAKEQ_MAX; have = true; }
            LightLock_Unlock(&sBakeQLock);
            if (!have) break;
            uint32_t ok = bakeBuildSlot(job.slot, job.src, job.sw, job.sh, job.Nu, job.Nv, job.bw, job.bh, sWMip0, sWMip1, sWSwz);
            linearFree(job.src);
            // PUBLISH only on success; on OOM (ok==0) leave the entry BUILDING (slot=-2) — the facade
            // stays raw (no crash). The reserved slot/budget leak, but OOM bakes are rare and a striped
            // facade beats a data abort. (release-store so regFind's acquire-load sees the built texture.)
            if (ok && job.ri >= 0 && job.ri < BAKE_CAP)
                __atomic_store_n(&sReg[job.ri].slot, (int16_t)job.slot, __ATOMIC_RELEASE);
        }
    }
}

static void bakeThreadStart(void) {
    // ★ §32.5: on OG-3DS gate the facade bake ENTIRELY OFF — no bakes, no worker. OG can't afford the bake
    // pool RAM, and the bake worker would seize core 1 + APT(30), colliding with the audio thread's own
    // core-1 APT (§20.18 last-writer-wins) → audio stutter. So on OG: facades render RAW (the §20 f24 stripe
    // at glancing angles — acceptable on the compromise tier) and core 1 is left wholly to audio. New-3DS
    // keeps the bake on the free spare core 2. [Provisional — OG path untested without hardware.]
    { bool isN3ds = false; APT_CheckNew3DS(&isN3ds); if (!isN3ds) { sAutoBake = 0; return; } }
    int on = 1;
    FILE *f = fopen("sdmc:/3ds/perfectdark/bakethread.txt", "r");
    if (f) { int v; if (fscanf(f, "%d", &v) == 1) on = (v != 0); fclose(f); }
    if (!on) return;
    sWMip0 = (uint32_t *)linearAlloc(BAKE_THREAD_DIM * BAKE_THREAD_DIM * sizeof(uint32_t));
    sWMip1 = (uint32_t *)linearAlloc(BAKE_THREAD_DIM * BAKE_THREAD_DIM * sizeof(uint32_t));
    sWSwz  = (uint16_t *)linearAlloc(BAKE_THREAD_DIM * BAKE_THREAD_DIM * sizeof(uint16_t));
    if (!sWMip0 || !sWMip1 || !sWSwz) {  // OOM → stay synchronous
        if (sWMip0) linearFree(sWMip0); if (sWMip1) linearFree(sWMip1); if (sWSwz) linearFree(sWSwz);
        sWMip0 = sWMip1 = NULL; sWSwz = NULL; return;
    }
    LightLock_Init(&sBakeQLock);
    LightEvent_Init(&sBakeWake, RESET_ONESHOT);
    sBakeQuit = false;
    s32 prio = 0x30; svcGetThreadPriority(&prio, CUR_THREAD_HANDLE);
    prio += 2; if (prio > 0x3F) prio = 0x3F;          // LOW priority — spare cycles, never preempts game/audio
    bool isN3ds = false; APT_CheckNew3DS(&isN3ds);
    int core = isN3ds ? 2 : 1;                         // spare app core (N3DS) / system core (OG)
    if (core == 1) APT_SetAppCpuTimeLimit(30);
    sBakeWorker = threadCreate(bakeWorkerMain, NULL, 64 * 1024, prio, core, false);
    if (!sBakeWorker) sBakeWorker = threadCreate(bakeWorkerMain, NULL, 64 * 1024, prio, -2, false); // app-core fallback
    sBakeThreadOn = (sBakeWorker != NULL);
    if (!sBakeThreadOn) { linearFree(sWMip0); linearFree(sWMip1); linearFree(sWSwz); sWMip0 = sWMip1 = NULL; sWSwz = NULL; }
#if PD_DEBUG3DS
    { char b[80]; snprintf(b, sizeof(b), "BAKETHREAD core=%d n3ds=%d on=%d", core, (int)isN3ds, (int)sBakeThreadOn); plat3dsBootLog(b); }
#endif
}
#endif // PD_BAKE_THREAD

// Content-keyed bake for source slot `src`. If a bake already exists for this CONTENT (even
// from a different slot before a cache wipe), re-use it — no rebuild. Otherwise create one
// (moderate size + box-filtered RGBA4 mip chain) and register it by hash. Returns the baked
// pool slot (and the residual-tiling divisor via *bdivU/*bdivV), or -1 → non-baked path.
static int bakeGetOrCreate(int src, int spanNu, int spanNv, float *bdivU, float *bdivV, bool createOK) {
    if (src <= 0 || src >= TEX_POOL_SIZE || !sBakeHash[src]) return -1;
    const uint32_t sw = sBakeSrcW[src], sh = sBakeSrcH[src];
    int ri = regFind(sBakeHash[src], (uint16_t)sw, (uint16_t)sh);
    if (ri >= 0) { // REUSE — survives slot churn / cache wipe; no rebuild, no twitch, no freeze.
        // ★ Unconditional on span AND on gen_mipmaps: once a facade's content is baked, EVERY
        // bind of that content samples the bake — even a re-import WITHOUT the N64 LOD bit
        // (gfx_pc toggles gen_mipmaps per bind as camera LOD changes) and even the low-span
        // slices gfx_pc splits off head-on. Gating reuse on either re-stripes the facade and
        // flips it baked<->raw as the camera moves (the "stripes after a pause" regression).
        // REUSE needs only the content hash — no kept source copy required. Span/gen_mipmaps
        // gate CREATION only (below).
        sReg[ri].lastUse = sBakeFrame;
        *bdivU = (float)sReg[ri].Nu; *bdivV = (float)sReg[ri].Nv;
        return sReg[ri].slot;
    }
    // ── create (first time this content is seen) — needs the kept source copy, which we keep
    //    ONLY for gen_mipmaps (facade) imports, so only facades ever CREATE a bake ──
    if (!createOK || !sBakeSrc[src]) return -1;      // low-span / non-facade first sighting → no bake yet
    if (sBakePendingCount > 0) return -1;            // don't create while old bakes pending-free (no 2× peak)
#if PD_BAKE_THREAD
    if (!sBakeThreadOn && sBakeThisFrame >= BAKE_PERFRAME) return -1; // sync throttle; the worker spreads itself
#else
    if (sBakeThisFrame >= BAKE_PERFRAME) return -1;
#endif
    if (regFindAny(sBakeHash[src], (uint16_t)sw, (uint16_t)sh) >= 0) return -1; // already ready OR building → raw
    if (sw == 0 || sh == 0) return -1;
    (void)sBakeTarget; // (baketarget.txt knob retired — per-axis cap is now BAKE_MAXDIM + the texel budget)
    int Nu = spanNu, Nv = spanNv; if (Nu < 1) Nu = 1; if (Nv < 1) Nv = 1;
    if (Nu > 128) Nu = 128; if (Nv > 128) Nv = 128;  // uint8_t reg field
    if (Nu == 1 && Nv == 1) return -1;               // not tiled → nothing to gain
    // ── SIZE THE BAKE — two regimes (CLAUDE.md §21 + 2026-06-08 native-density rework) ────────────────
    // The bake pre-tiles the source so a facade's huge tiled UV (0..N → f24 stripe) samples a SMALL residual
    // UV instead. How many tiles to bake depends on whether mips are on:
    //  • MIPS ON (legacy): pre-tile the FULL Nu×Nv and DOWNSAMPLE to fit → residual UV ÷Nu = [0,1] so the
    //    mip chain engages and area-averages. Costs resolution (the soft "filtered/low-res" facades).
    //  • MIPS OFF (the default now — there is NO mip to feed): pre-tile only as many copies as fit at NATIVE
    //    texel density (POT), and let the bake's REPEAT wrap tile the rest via a SMALL residual UV (÷bakeNu).
    //    ★ Native texel density = SHARP, and a small residual magnitude (≈Nu/bakeNu, e.g. 44/8≈5.5 ≪ the
    //    13-19 that stripes) keeps the f24 stripe away. The downsample was ONLY ever to make the (now-absent)
    //    mip engage — with mips off it threw away resolution for nothing. This is THE fix for low-res bakes.
    int bakeNu = Nu, bakeNv = Nv;
    uint32_t bw, bh;
    if (!sMipsEnabled) {
        int pNu = 1; while (pNu * 2 <= Nu) pNu <<= 1;   // largest POT ≤ Nu (so sw*bakeNu stays POT)
        int pNv = 1; while (pNv * 2 <= Nv) pNv <<= 1;
        bakeNu = pNu; bakeNv = pNv;
        while (sw * (uint32_t)bakeNu > BAKE_MAXDIM && bakeNu > 1) bakeNu >>= 1;
        while (sh * (uint32_t)bakeNv > BAKE_MAXDIM && bakeNv > 1) bakeNv >>= 1;
        while ((size_t)(sw * (uint32_t)bakeNu) * (sh * (uint32_t)bakeNv) > (size_t)MIP_LIN_TEXELS) {
            if (bakeNu >= bakeNv && bakeNu > 1) bakeNu >>= 1;
            else if (bakeNv > 1) bakeNv >>= 1;
            else break;                                  // single tile already over budget → clamp below
        }
        // (The 128px square-bake cap that lived here is removed now that the linear heap is 48 MB + the bake
        // budget is 26 MB — a full level's FULL native-res facades fit with no skips, so there's no reason to
        // cap. If a future level ever overflows 26 MB, re-add: `if (sw*bakeNu>128 && sh*bakeNv>128) halve both`.)
        bw = sw * (uint32_t)bakeNu; bh = sh * (uint32_t)bakeNv;   // NATIVE texel density (no downsample, no cap)
    } else {
        bw = sw * (uint32_t)Nu; bh = sh * (uint32_t)Nv;          // legacy: full tiling, downsample-to-fit
        while (bw > BAKE_MAXDIM) bw >>= 1;
        while (bh > BAKE_MAXDIM) bh >>= 1;
        while ((size_t)bw * bh > MIP_LIN_TEXELS) { if (bw >= bh && bw > 8) bw >>= 1; else if (bh > 8) bh >>= 1; else break; }
    }
    if (bw < 8) bw = 8; if (bh < 8) bh = 8;          // 8x8 swizzle-tile minimum
    while ((size_t)bw * bh > MIP_LIN_TEXELS) { if (bw >= bh && bw > 8) bw >>= 1; else if (bh > 8) bh >>= 1; else break; } // safety
    const size_t newBytes = (size_t)bw * bh * 2u;    // 16-bit (RGB565 opaque / RGBA4 alpha)
    if (sBakeActive >= BAKE_CAP || sBakeBytes + newBytes > BAKE_MEM_BUDGET) { sBakeSkip++; return -1; }
    ri = regAlloc(); if (ri < 0) { sBakeSkip++; return -1; }   // working set full → skip (no eviction)
    int slot = bakeAllocSlot(); if (slot <= 0) return -1;
    // ── reserve the registry entry (common to both paths). lastUse fresh → regAlloc won't reclaim it. ──
    sReg[ri].hash = sBakeHash[src]; sReg[ri].srcW = (uint16_t)sw; sReg[ri].srcH = (uint16_t)sh;
    // Store the BAKED tile count (bakeNu/bakeNv) — it IS the residual divisor (the draw divides UV by it and
    // REPEAT-wraps the rest). For mips-on it equals Nu/Nv; for mips-off it's the native-density partial count.
    sReg[ri].Nu = (uint8_t)bakeNu; sReg[ri].Nv = (uint8_t)bakeNv; sReg[ri].bytes = (uint32_t)newBytes;
    sReg[ri].lastUse = sBakeFrame;
    sBakeActive++; sBakeBytes += newBytes;
    *bdivU = (float)bakeNu; *bdivV = (float)bakeNv;
#if PD_BAKE_THREAD
    if (sBakeThreadOn && (bakeNu > 2 || bakeNv > 2)) {  // only TILED towers go async (the burst pause); 2×2 minified → sync
        // ASYNC: copy the small POT source + queue the job. The facade draws RAW (regFind requires
        // slot >= 0) until the worker builds + release-publishes the slot.
        uint32_t *cp = (uint32_t *)linearAlloc((size_t)sw * sh * sizeof(uint32_t));
        bool queued = false;
        if (cp) {
            memcpy(cp, sBakeSrc[src], (size_t)sw * sh * sizeof(uint32_t));
            LightLock_Lock(&sBakeQLock);
            int nt = (sBakeQTail + 1) % BAKEQ_MAX;
            if (nt != sBakeQHead) {
                BakeJob *j = &sBakeQ[sBakeQTail];
                j->src = cp; j->sw = (uint16_t)sw; j->sh = (uint16_t)sh; j->Nu = (uint8_t)bakeNu; j->Nv = (uint8_t)bakeNv;
                j->bw = (uint16_t)bw; j->bh = (uint16_t)bh; j->slot = slot; j->ri = ri;
                sBakeQTail = nt; queued = true;
            }
            LightLock_Unlock(&sBakeQLock);
            if (!queued) linearFree(cp);
        }
        if (queued) {
            sReg[ri].slot = -2;            // BUILDING — redirect waits for the worker's publish
            LightEvent_Signal(&sBakeWake);
            return -1;
        }
        // queue full (≤32 in flight) or linearAlloc failed → fall through to a SYNCHRONOUS build below.
        // Bounds in-flight memory (no OOM pile-up) and still bakes the facade (a brief dip, not a freeze).
    }
#endif
    // SYNC: build inline on the main thread, then publish the slot.
    if (!bakeBuildSlot(slot, sBakeSrc[src], sw, sh, bakeNu, bakeNv, bw, bh, sMipLin0, sMipLin1, (uint16_t *)sTexScratch)) {
        // OOM (C3D_TexInitMipmap failed) → roll back the reservation cleanly (main thread) and skip.
        sReg[ri].hash = 0; sReg[ri].slot = -1;
        sBakeActive--; sBakeBytes -= newBytes; bakeReturnSlot(slot); sBakeSkip++;
        return -1;
    }
    sReg[ri].slot = (int16_t)slot;
    sBakeThisFrame++;
#if PD_DEBUG3DS
    { char bb[160]; snprintf(bb, sizeof(bb), "BAKEDIM addr=%p src=%ux%u -> baked=%ux%u Nu=%d Nv=%d KB=%u(+mips)",
        (void *)sTexSrcAddr[src], (unsigned)sw, (unsigned)sh, (unsigned)bw, (unsigned)bh, Nu, Nv, (unsigned)(newBytes >> 10));
      plat3dsBootLog(bb); }
#endif
    return slot;
}

// ── load-time facade registry (Stage B) ──────────────────────────────────────
// The level loader (bgLoadRoom scan, src/game/bg.c) registers each tiled-facade SOURCE
// texture by its decoded-data address — which is exactly gfx_pc's texture_addr cache key
// (gDPSetTextureImage uses tex->data) — together with the EXACT tile count from geometry.
// gfx_pc arms the next upload by that address; upload_texture then bakes deterministically
// (downsample-to-fit) with the load-time Nu/Nv, EVEN for non-tex_lod facades the per-draw
// renderer heuristic could never bake (the 2c798123 tower). Address-keyed → the seam is a
// plain pointer shared across the game↔renderer boundary; no content-hash matching needed.
#define FACADE_TBL_MAX 1024
typedef struct { uintptr_t addr; uint16_t cu, cv; } FacadeEnt; // cu/cv = ceil(tiles) from geometry
static FacadeEnt sFacTbl[FACADE_TBL_MAX];
static int       sFacTblCount = 0;
static int       sFacUpCu = 0, sFacUpCv = 0; // armed for the next upload_texture (0 = not a facade)

extern "C" void gfx_texture_cache_delete(const uint8_t *orig_addr); // gfx_pc.cpp — drop a cache entry by addr

// ★ DETERMINISTIC BAKE RULE (CLAUDE.md §21.9): a texture bakes IFF it is registered as a facade
// (by geometry tiling) anywhere in the level — independent of load order, cache state, or scan
// timing. For that, registration must GUARANTEE the bake. The gap was: a SHARED texture first used
// in a NON-facade room gets decoded+cached `isFacade=0` before its facade room ever registers it,
// and a later cache HIT never re-arms it → it never bakes. Fix: registration QUEUES a cache
// invalidation for that texture; pdFacadeFlushInvalidations (called at a safe point — between the
// pre-warm passes) drops the stale entry so its next import re-decodes into a FRESH slot, sees it's
// now registered, and bakes. DEFERRED because pdFacadeRegister is called from inside draw_triangles
// (the render-time register pass) and gfx_texture_cache_delete→gfx_flush→draw_triangles would
// re-enter. Safe: a fresh re-decode, NOT an in-place C3D_TexDelete of a live texture.
#define PENDING_INVAL_MAX 1024
static uintptr_t sPendingInval[PENDING_INVAL_MAX];
static int       sPendingInvalN = 0;
static void pdFacadeQueueInval(uintptr_t addr) {
    for (int i = 0; i < sPendingInvalN; i++) if (sPendingInval[i] == addr) return;
    if (sPendingInvalN < PENDING_INVAL_MAX) sPendingInval[sPendingInvalN++] = addr;
}
extern "C" void pdFacadeFlushInvalidations(void) {
    for (int i = 0; i < sPendingInvalN; i++) gfx_texture_cache_delete((const uint8_t *)sPendingInval[i]);
    sPendingInvalN = 0;
}
extern "C" void pdFacadeRegister(uintptr_t addr, int ceilU, int ceilV) {
    if (!addr || ceilU < 1 || ceilV < 1 || (ceilU <= 1 && ceilV <= 1)) return;
    for (int i = 0; i < sFacTblCount; i++) if (sFacTbl[i].addr == addr) {
        bool grew = false;
        if (ceilU > sFacTbl[i].cu) { sFacTbl[i].cu = (uint16_t)ceilU; grew = true; }
        if (ceilV > sFacTbl[i].cv) { sFacTbl[i].cv = (uint16_t)ceilV; grew = true; }
        if (grew) pdFacadeQueueInval(addr); // bigger tiling → old bake stale
        return;
    }
    if (sFacTblCount < FACADE_TBL_MAX) {
        sFacTbl[sFacTblCount].addr = addr;
        sFacTbl[sFacTblCount].cu = (uint16_t)ceilU;
        sFacTbl[sFacTblCount].cv = (uint16_t)ceilV;
        sFacTblCount++;
        pdFacadeQueueInval(addr); // re-decode+bake if it was cached unbaked
    }
}
static int facTblHas(uintptr_t addr) { for (int i = 0; i < sFacTblCount; i++) if (sFacTbl[i].addr == addr) return 1; return 0; }


// ── per-pass facade UV accumulator (the SPLIT-BATCH fix, CLAUDE.md §21.9) ───────────────────────
// A facade's tiling is frequently SPLIT across many vertex batches (gfx_pc re-batches geometry), so
// no single draw_triangles call sees the full S/T span — a per-batch span test undercounts and the
// facade never registers (this was "the one outlier building": phase=2 BG geometry, its room IS
// pre-warmed, yet each batch only spans ~1×). FIX: during the register pass, ACCUMULATE global
// min/max U,V per texture SOURCE ADDRESS across every batch; at pass end, register textures whose
// TOTAL span tiles ≥ BAKE_SPAN_MIN. This mirrors bg.c's per-texture scan accumulation but render-
// time, so it sees sub-display-lists too. Reset at pass start, flushed by pdFacadeRegAccFlush.
#define REG_ACC_MAX 512
static struct RegAcc { uintptr_t addr; float umn, umx, vmn, vmx; } sRegAcc[REG_ACC_MAX];
static int sRegAccN = 0;
static void pdFacadeRegAccReset(void) { sRegAccN = 0; }
static void pdFacadeRegAccum(uintptr_t addr, float umn, float umx, float vmn, float vmx) {
    if (!addr) return;
    for (int i = 0; i < sRegAccN; i++) if (sRegAcc[i].addr == addr) {
        if (umn < sRegAcc[i].umn) sRegAcc[i].umn = umn;
        if (umx > sRegAcc[i].umx) sRegAcc[i].umx = umx;
        if (vmn < sRegAcc[i].vmn) sRegAcc[i].vmn = vmn;
        if (vmx > sRegAcc[i].vmx) sRegAcc[i].vmx = vmx;
        return;
    }
    if (sRegAccN < REG_ACC_MAX) {
        sRegAcc[sRegAccN].addr = addr;
        sRegAcc[sRegAccN].umn = umn; sRegAcc[sRegAccN].umx = umx;
        sRegAcc[sRegAccN].vmn = vmn; sRegAcc[sRegAccN].vmx = vmx;
        sRegAccN++;
    }
}
// Register every accumulated texture whose TOTAL (across-batch) span tiles heavily. Called from bg.c
// between pass 1 (register) and the invalidation flush, so pass 2 (decode) bakes the now-registered.
extern "C" void pdFacadeRegAccFlush(void) {
    for (int i = 0; i < sRegAccN; i++) {
        float uSpan = sRegAcc[i].umx - sRegAcc[i].umn;
        float vSpan = sRegAcc[i].vmx - sRegAcc[i].vmn;
        if (uSpan > sBakeSpanMin || vSpan > sBakeSpanMin) {
            int cu = (uSpan > 1.5f) ? (int)ceilf(uSpan) : 1;
            int cv = (vSpan > 1.5f) ? (int)ceilf(vSpan) : 1;
            pdFacadeRegister(sRegAcc[i].addr, cu, cv);
#if PD_DEBUG3DS
            { char rb[120]; snprintf(rb, sizeof(rb), "REGACC addr=%p us=%.1f vs=%.1f cu=%d cv=%d",
                (void *)sRegAcc[i].addr, uSpan, vSpan, cu, cv); plat3dsBootLog(rb); }
#endif
        }
    }
    sRegAccN = 0;
}
// Called by gfx_pc::import_texture right before upload_texture, with the texture source addr.
extern "C" void pdFacadeArmUpload(uintptr_t addr) {
    sPendingUploadAddr = addr;                  // recorded for EVERY upload (facade or not)
    sFacUpCu = sFacUpCv = 0;
    if (!addr) return;
    for (int i = 0; i < sFacTblCount; i++) if (sFacTbl[i].addr == addr) {
        sFacUpCu = sFacTbl[i].cu; sFacUpCv = sFacTbl[i].cv; return;
    }
}

static void gfx_citro3d_upload_texture(const uint8_t *rgba32, uint32_t width, uint32_t height, bool gen_mipmaps) {
    int id = sCurTexId;
    if (id <= 0 || id >= TEX_POOL_SIZE) return;
#ifdef BK_TRACE
    /* TEMP (flat-foreground hunt): content variance of uploads — is the
     * DECODED texture detailed or uniform on this target? */
    static int sUpN = 0;
    if (sUpN++ < 900) {
        const uint32_t *px = (const uint32_t *)rgba32;
        uint32_t n = width * height, mn = 0xFFFFFFFF, mx = 0, acc = 0;
        for (uint32_t k = 0; k < n; k++) {
            uint32_t lum = (px[k] & 0xFF) + ((px[k] >> 8) & 0xFF) + ((px[k] >> 16) & 0xFF);
            if (lum < mn) mn = lum;
            if (lum > mx) mx = lum;
            acc ^= px[k] * (k | 1);
        }
        BK_TR(BK_TR_DRAW, "UPLOAD id=%d %ux%u mips=%d lum[%u,%u] hash=%08x",
              id, width, height, (int)gen_mipmaps, mn, mx, acc);
        /* dump the suspect ids' decoded RGBA32 to SD for visual inspection
         * (flat-foreground hunt: detailed fur vs near-uniform decode?) */
        if (id == 458 || id == 496 || id == 523 || id == 527) {
            char fp[64];
            static int sDumped[4] = { 0, 0, 0, 0 };
            int di = (id == 458) ? 0 : (id == 496) ? 1 : (id == 523) ? 2 : 3;
            if (!sDumped[di]) {
                sDumped[di] = 1;
                snprintf(fp, sizeof(fp), "sdmc:/3ds/banjo/tex%d_%ux%u.raw", id, width, height);
                FILE *tf = fopen(fp, "wb");
                if (tf) { fwrite(rgba32, 4, (size_t)width * height, tf); fclose(tf); }
            }
        }
    }
#endif
    const bool isFacade = (sFacUpCu > 1 || sFacUpCv > 1); // armed by gfx_pc from the load-time table
    const int facCu = sFacUpCu, facCv = sFacUpCv;
    sTexSrcAddr[id] = sPendingUploadAddr; sPendingUploadAddr = 0; // remember this texid's source addr (seam)
    sFacUpCu = sFacUpCv = 0; // consume the arm

    uint32_t pw = nextPOT(width), ph = nextPOT(height);
    if (pw > 1024) pw = 1024;
    if (ph > 1024) ph = 1024;

    // ★ OG-3DS lomem: pick the 16-bit format for this texture. Opaque (all alpha==0xFF) -> RGB565 (5/6/5,
    // no banding); has-alpha -> RGBA4 (4-bit alpha, carries translucency). N3DS keeps RGBA8 (loFmt unused).
    bool texOpaque = true;
    GPU_TEXCOLOR loFmt = GPU_RGB565;
    if (sLomem) {
        const uint32_t *sc = (const uint32_t *)rgba32;
        const uint32_t n = width * height;
        for (uint32_t i = 0; i < n; i++) if ((sc[i] >> 24) != 0xFFu) { texOpaque = false; break; }
        loFmt = texOpaque ? GPU_RGB565 : GPU_RGBA4;
    }

    if (pw == width && ph == height) {
        swizzleTexture(rgba32, sTexScratch, width, height);
        sTexScaleS[id] = 1.f; sTexScaleT[id] = 1.f;
    } else {
        // Round up to POT, wrapping source texels into the pad so REPEAT works.
        const uint32_t *s = (const uint32_t *)rgba32;
        uint32_t offs = 0;
        for (uint32_t y = 0; y < ph; y += 8) {
            for (uint32_t x = 0; x < pw; x += 8) {
                for (int i = 0; i < 64; i++) {
                    int x2 = i & 7, y2 = i >> 3;
                    uint32_t rx = (x + x2) % width, ry = (y + y2) % height;
                    int pos = sTileOrder[(x2 & 3) + ((y2 & 3) << 2)] + ((x2 >> 2) << 4) + ((y2 >> 2) << 5);
                    sTexScratch[offs + pos] = rgba_to_abgr(s[ry * width + rx]);
                }
                offs += 64;
            }
        }
        sTexScaleS[id] = (float)width / (float)pw;
        sTexScaleT[id] = (float)height / (float)ph;
    }

    // §21.11 — HONOR THE N64 tex_lod BIT: the game flags textures it wants mip/LOD on (distant
    // surfaces) via G_TL_LOD; gfx_pc passes it here as gen_mipmaps. The PC reference gates mips+aniso
    // on exactly this bit. We give those level textures a real mip chain so the PICA's hardware LOD
    // area-averages them at distance → kills minification aliasing GENERALLY (not just the one tower).
    // This is the robust, game-authored signal — vs the render-time heuristic mip-bake (which stays as
    // the fallback for facades PD UNDER-flags, e.g. the point-filtered 0xae93464). Facades (isFacade)
    // go to the bake path (own mips); only NON-facade tex_lod textures take this path. Capped at
    // MIP_LIN_TEXELS (the box-filter scratch) and >=16px; mips cost ~33% so it's gated + measured.
    sTexHasMips[id] = false;
    // Mip a NON-facade level texture the game flags for LOD (gen_mipmaps = N64 tex_lod). Facades go to
    // the bake path (own mips); the minified point facades PD under-flags go to the 2×2 mip-bake (above).
    const bool wantMips = sMipsEnabled && sTexLodMips && gen_mipmaps && !isFacade &&
                          pw >= 16 && ph >= 16 && (size_t)pw * ph <= MIP_LIN_TEXELS;
    if (sTexValid[id]) C3D_TexDelete(&sTexPool[id]);
    sTexValid[id] = false; // invalid until a successful (re)init — so an OOM bail below leaves it skippable, not stale
    if (wantMips) {
        const uint32_t *src = (const uint32_t *)rgba32;
        for (uint32_t y = 0; y < ph; y++)
            for (uint32_t x = 0; x < pw; x++)
                sMipLin0[y * pw + x] = src[(y % height) * width + (x % width)]; // linear POT (wrap into pad)
        const int maxLevel = C3D_TexCalcMaxLevel(pw, ph);
        // ★ OOM GUARD (real-HW #84, level-4 cinematic): C3D_TexInitMipmap linearAllocs the texture; on
        // FCRAM exhaustion it returns false WITHOUT allocating → the C3D_TexLoadImage memcpy below would
        // write into NULL (data abort, FAR≈8). Skip the texture instead of crashing (it draws untextured —
        // applyCmdState checks sTexValid before binding). Same class as the §23.2 bake guard, on the
        // normal upload path (which was unguarded). Mandarine's larger heap masks this → HW-only.
        if (!C3D_TexInitMipmap(&sTexPool[id], (u16)pw, (u16)ph, sLomem ? loFmt : GPU_RGBA8)) {
            sTexOomCount++; // production memlog counter
#if PD_DEBUG3DS
            { char b[80]; snprintf(b, sizeof(b), "TEXOOM mip id=%d %ux%u freeKB=%u", id, (unsigned)pw, (unsigned)ph, (unsigned)(linearSpaceFree() >> 10)); plat3dsBootLog(b); }
#endif
            return;
        }
        for (int Lv = 0; Lv <= maxLevel; Lv++) {
            const uint32_t lw = pw >> Lv, lh = ph >> Lv, box = 1u << Lv, nn = box * box;
            const uint32_t *lin = sMipLin0;
            if (Lv > 0) { // box-filter level 0 down to level Lv (area-average)
                for (uint32_t y = 0; y < lh; y++)
                    for (uint32_t x = 0; x < lw; x++) {
                        uint32_t ar=0, ag=0, ab=0, aa=0;
                        for (uint32_t by = 0; by < box; by++)
                            for (uint32_t bx = 0; bx < box; bx++) {
                                uint32_t c = sMipLin0[(y*box+by)*pw + (x*box+bx)];
                                ar += c&0xff; ag += (c>>8)&0xff; ab += (c>>16)&0xff; aa += (c>>24)&0xff;
                            }
                        sMipLin1[y*lw + x] = (ar/nn) | ((ag/nn)<<8) | ((ab/nn)<<16) | ((aa/nn)<<24);
                    }
                lin = sMipLin1;
            }
            swizzleTexture((const uint8_t *)lin, sTexScratch, lw, lh);
            if (sLomem) scratchToLo16(lw * lh, texOpaque);  // RGBA8 scratch -> 16-bit in place (OG budget)
            C3D_TexLoadImage(&sTexPool[id], sTexScratch, GPU_TEXFACE_2D, Lv);
        }
        C3D_TexFlush(&sTexPool[id]);
        sTexHasMips[id] = true;
        sTexMipCount++; sTexMipBytes += (size_t)pw * ph * 4 / 3; // ~33% chain
    } else {
        if (sLomem) scratchToLo16((uint32_t)pw * ph, texOpaque);  // RGBA8 scratch -> 16-bit in place (OG budget)
        // ★ OOM GUARD (real-HW #84): see the mip branch above — skip on FCRAM exhaustion, don't memcpy into NULL.
        if (!C3D_TexInit(&sTexPool[id], pw, ph, sLomem ? loFmt : GPU_RGBA8)) { // N3DS: full RGBA8; OG: 16-bit
            sTexOomCount++; // production memlog counter
#if PD_DEBUG3DS
            { char b[80]; snprintf(b, sizeof(b), "TEXOOM id=%d %ux%u freeKB=%u", id, (unsigned)pw, (unsigned)ph, (unsigned)(linearSpaceFree() >> 10)); plat3dsBootLog(b); }
#endif
            return;
        }
        C3D_TexUpload(&sTexPool[id], sTexScratch);
        C3D_TexFlush(&sTexPool[id]);
    }
    sTexValid[id] = true;

    // ── content-keyed bake bookkeeping (FACADES ONLY — no draw-time fallback) ──────────────
    // ★ The ONLY way a bake is ever created is the LOAD-TIME facade scan (src/game/bg.c →
    // pdFacadeRegister → pdFacadeArmUpload → isFacade here). draw_triangles NEVER creates a bake
    // (createOK=false). This is what makes it flare-safe BY CONSTRUCTION: flares/glares are
    // appended at RENDER time (bgRenderArtifacts) and use a dedicated texture set — they are NOT
    // in the static room mesh the loader scans, so they can never be registered, never armed,
    // never hashed/copied/baked. We therefore keep a source copy + hash ONLY for registered
    // facades (not every small texture) — that also reclaims the ~1-2 MB of copies that fed the
    // building-interior OOM. The content HASH is what lets the bake survive gfx_pc slot churn /
    // cache wipes: a re-import of the same facade content re-finds its registry bake (regFind),
    // no rebuild, no flip. See CLAUDE.md §20.19.
    if (sBakeSrc[id]) { free(sBakeSrc[id]); sBakeSrc[id] = NULL; }
    sBakeHash[id] = 0; sBakeSrcW[id] = 0; sBakeSrcH[id] = 0;
    if (sAutoBake && isFacade && pw <= BAKE_SRC_MAX && ph <= BAKE_SRC_MAX) {
        const uint32_t *s = (const uint32_t *)rgba32;
        // FNV-1a over the wrapped POT view (matches bakeHash over the kept copy's layout).
        uint32_t h = 2166136261u;
        for (uint32_t y = 0; y < ph; y++)
            for (uint32_t x = 0; x < pw; x++) { h ^= s[(y % height) * width + (x % width)]; h *= 16777619u; }
        sBakeHash[id] = h ? h : 1u;
        sBakeSrcW[id] = (uint16_t)pw; sBakeSrcH[id] = (uint16_t)ph;
        uint32_t *copy = (uint32_t *)malloc((size_t)pw * ph * 4);
        if (copy) {
            for (uint32_t y = 0; y < ph; y++)
                for (uint32_t x = 0; x < pw; x++)
                    copy[y * pw + x] = s[(y % height) * width + (x % width)]; // wrap into POT pad
            sBakeSrc[id] = copy;
        }
        // Deterministic LOAD-TIME bake with the exact tile count from geometry. Created ONCE,
        // at load (outside the render loop), so there's no runtime stutter; draw_triangles then
        // only ever REUSES it. Works for ANY facade, tex_lod or not (the non-tex_lod towers).
        if (sBakeSrc[id]) {
            int spanNu = (int)nextPOT((uint32_t)(facCu > 1 ? facCu : 1));
            int spanNv = (int)nextPOT((uint32_t)(facCv > 1 ? facCv : 1));
            float du = 1.f, dv = 1.f;
            sBakeThisFrame = 0;      // load happens outside the render loop → don't let the
                                     // per-frame create budget (BAKE_PERFRAME) skip facades
            bakeGetOrCreate(id, spanNu, spanNv, &du, &dv, true);
        }
    }
#if PD_DEBUG3DS
    // SMALLTEX: trace every small (bake-candidate) texture's FIRST upload — was it armed as a
    // facade at upload time, and did it bake? Cross-reference with FACSCAN (registered) + RAWFACE
    // (drawn-unbaked): a texture in FACSCAN but here isFacade=0 = the COVERAGE GAP (its texture
    // was uploaded/cached BEFORE its room's scan registered it). Deduped by source address.
    if (pw <= BAKE_SRC_MAX && ph <= BAKE_SRC_MAX) {
        static uintptr_t sSeen[1024]; static int sSeenN = 0;
        uintptr_t a = sTexSrcAddr[id]; int dup = 0, k;
        for (k = 0; k < sSeenN; k++) if (sSeen[k] == a) { dup = 1; break; }
        if (!dup && sSeenN < 1024) {
            sSeen[sSeenN++] = a;
            char bb[160];
            snprintf(bb, sizeof(bb), "SMALLTEX addr=%p isFacade=%d cu=%d cv=%d %ux%u genmip=%d baked=%d",
                (void *)a, (int)isFacade, facCu, facCv, (unsigned)pw, (unsigned)ph, (int)gen_mipmaps, (sBakeHash[id] != 0));
            plat3dsBootLog(bb);
        }
    }
#endif
}

static GPU_TEXTURE_WRAP_PARAM cmToPica(uint32_t cm) {
    switch (cm) {
        case G_TX_NOMIRROR | G_TX_CLAMP: return GPU_CLAMP_TO_EDGE;
        case G_TX_MIRROR | G_TX_WRAP:    return GPU_MIRRORED_REPEAT;
        case G_TX_MIRROR | G_TX_CLAMP:   return GPU_MIRRORED_REPEAT;
        case G_TX_NOMIRROR | G_TX_WRAP:
        default:                         return GPU_REPEAT;
    }
}

static void gfx_citro3d_set_sampler_parameters(int tile, bool linear, uint32_t cms, uint32_t cmt, bool mipmaps) {
    (void)mipmaps;
    int id = stTexUnit[tile];
    if (id <= 0 || id >= TEX_POOL_SIZE || !sTexValid[id]) return;
    GPU_TEXTURE_FILTER_PARAM f = linear ? GPU_LINEAR : GPU_NEAREST;
    C3D_TexSetFilter(&sTexPool[id], f, f);
    sTexFiltLinear[id] = linear ? 1 : 0; // §7.1.3-class: record per-id so replay re-asserts THIS draw's filter
    // §21.11: if this texture got a tex_lod mip chain, enable the PICA's LOD filter so the mips engage.
    // NEAREST keeps the crunchy N64 pixels within a level while mips still kill minification aliasing.
    if (sTexHasMips[id]) C3D_TexSetFilterMipmap(&sTexPool[id], sMipNearest ? GPU_NEAREST : GPU_LINEAR);
    sTexWrapS[id] = cmToPica(cms); sTexWrapT[id] = cmToPica(cmt);
    C3D_TexSetWrap(&sTexPool[id], sTexWrapS[id], sTexWrapT[id]);
    sTexTilesS[id] = ((cms & G_TX_CLAMP) == 0); // tiling (repeat/mirror) axes → bake candidate
    sTexTilesT[id] = ((cmt & G_TX_CLAMP) == 0);
    stTexLinear[tile] = linear;
}

