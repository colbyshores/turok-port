typedef struct {
    uint32_t vboOffset;        // first vertex in the streaming VBO
    uint32_t vertCount;        // 3 * num_tris
    struct ShaderProgram *prg;
    uint32_t stageConst[6];    // per-STAGE TEV constants (ABGR8), composed per draw
                               // from the chain's cRgbSrc/cASrc sources
    int16_t  tex0, tex1;       // texture-pool ids (-1 = none)
    // depth state
    bool     depthTest, depthMask, depthCompare, depthDecal, depthSourcePrim, depthInter;
    // blend
    bool     useAlpha, modulate;
    uint8_t  chainSel;         // which TEV chain: 0=env, 1=envC, 2=envS (per-draw)
    // alpha test
    bool     alphaTest; uint8_t alphaRef;
    // viewport / scissor in gfx_pc draw-area coords (logical 400x240)
    int16_t  vpX, vpY, vpW, vpH;
    int16_t  scX, scY, scW, scH; bool scissorOn;
    bool     clearDepth;       // this cmd is a mid-frame depth-buffer reset (gun-on-top)
    bool     is2d;             // ★ 2D HUD/sprite (orthographic, vertex w==1) — replayed with NO stereo
                               // shear so it sits at the same screen pos in both eyes (flat, no ghosting)
    // §7.1 3b — framebuffer effects (scope/lens). fbOp=1 ⇒ this cmd is the copy_framebuffer STREAM-SPLIT
    // marker: end_frame splits the recorded stream here (scene → game-fb, then lens → eye). fbBind
    // (non-NULL) ⇒ this draw samples that FB tex as tex0 (FIX A: the lens samples sGameFbTex directly,
    // with a per-vertex UV remap in draw_triangles — no snapshot tex).
    uint8_t  fbOp;             // 0 = normal draw, 1 = framebuffer-copy (stream-split) marker
    C3D_Tex *fbBind;           // bind this C3D_Tex as tex0 instead of the pool tex (select_texture_fb)
    // ★ Per-draw texture WRAP, snapshotted at record time. The wrap physically lives in the SHARED
    // mutable sTexPool[id].param, which C3D_TexBind reloads — so at replay it would carry whatever the
    // LAST set_sampler_parameters left it, NOT this draw's wrap. Two draws sharing a texid with
    // different wraps (e.g. a CLAMP draw after a MIRROR lens-flare glare on the same texture) would make
    // the glare replay CLAMPED → its [-w,+w] mirror collapses to 4 un-mirrored corner pieces. Recording
    // the wrap per-cmd and re-asserting it at replay fixes this. 0xFF = leave as-is (fbBind / bake).
    uint8_t  wrapS0, wrapT0, wrapS1, wrapT1;
    // SAME §7.1.3 class for the min/mag FILTER + mip filter: set_sampler_parameters mutates the shared
    // sTexPool[id] filter, and C3D_TexBind reloads it — so without this snapshot a later same-texid draw's
    // filter (e.g. a LINEAR draw after this NEAREST one, or vice-versa) replays onto THIS draw → it reads
    // as the wrong sharpness / wrong mip level, intermittently (depends on draw order + texid reuse, which
    // churns with memory). Record the per-draw filter and re-assert it at replay. 0xFF = leave as-is.
    uint8_t  filt0, filt1;
    // FOG (§3.3/§20.12): the N64 per-draw fog state, snapshotted from set_fog. fogEnable ⇒ replay binds
    // the PICA fixed-function fog unit (a depth FogLut built from mul/offset + fogColor); else fog off.
    bool     fogEnable; int16_t fogMul, fogOffset; uint32_t fogColor; // fogColor = 0x00BBGGRR for C3D_FogColor
    bool     perVertexFog;     // this draw rides the fog factor on PRIMARY.a (per-vertex) in the appended fog
                               // TEV stage — opaque + texel-alpha translucent geom.
    bool     perDrawFog;       // shade-alpha draws (can't ride PRIMARY.a) instead use the fog TEV stage with a
                               // PER-DRAW constant factor (in stageConst[fog_stage].alpha). Together these two
                               // cover every opt_fog draw, so none falls back to the banding hardware FogLut.
} DrawCmd;

