// ── EFFECT FRAMEBUFFER POOL (§7.1). PD creates offscreen FBs (g_PrevFrameFb/g_BlurFb scope+blur,
//    g_MenuBlurFb/g_MenuScreenFb menu blur, the cloak FBs) via videoCreateFramebuffer → create_framebuffer.
//    Each is backed by a sample-able C3D_Tex (the color). Sample-only FBs (scope/blur/cloak — the game
//    COPIES the back-buffer in and SAMPLES it) use a plain linear tex; render-TO-FB FBs (menu blur) get a
//    VRAM tex + a C3D_RenderTarget (created lazily, later increment). id 0 = the main framebuffer. ──
typedef struct {
    bool     used;
    uint16_t w, h;        // requested logical size (0 = auto, resized by gfx_pc later)
    uint16_t potW, potH;  // POT-rounded tex allocation
    C3D_Tex  tex;
    bool     texInit;
    bool     renderTarget;
    bool     hasDepth;
} EffectFb;
static EffectFb sEffectFb[FB_POOL_SIZE];

static int gfx_citro3d_create_framebuffer(void) {
    for (int i = 1; i < FB_POOL_SIZE; i++) {     // id 0 reserved for the main (screen) framebuffer
        if (!sEffectFb[i].used) { memset(&sEffectFb[i], 0, sizeof(EffectFb)); sEffectFb[i].used = true; return i; }
    }
    return 0;   // pool full → fall back to main fb (the effect is silently disabled, no crash)
}
static void gfx_citro3d_update_framebuffer_parameters(int fb, uint32_t w, uint32_t h, uint32_t msaa,
        bool invert_y, bool render_target, bool depth, bool extract_depth) {
    (void)msaa; (void)invert_y; (void)extract_depth;
    if (fb <= 0 || fb >= FB_POOL_SIZE || !sEffectFb[fb].used) return;
    if (!gfx_framebuffers_enabled) return;       // effects off (default): allocate nothing — byte-identical to the old stub
    if (w == 0 || h == 0) return;                // not yet sized (auto-resize FBs get a real size later)
    EffectFb *f = &sEffectFb[fb];
    uint16_t potW = (uint16_t)nextPOT(w), potH = (uint16_t)nextPOT(h);
    if (potW < 8) potW = 8; if (potH < 8) potH = 8;
    if (potW > 1024) potW = 1024; if (potH > 1024) potH = 1024;
    if (f->texInit && f->potW == potW && f->potH == potH) { f->w = (uint16_t)w; f->h = (uint16_t)h; return; }
    // §7.1 VRAM reclaim: the FULL-FRAME sample FBs (g_PrevFrameFb/g_BlurFb, render_target, ~400×240) are
    // UNUSED on 3DS — the lens samples sGameFbTex and the blur samples sPrevSceneTex (their own VRAM texs),
    // and get_framebuffer_texture_id is never called (game_renders_to_framebuffer=false). Skipping their
    // ~0.5MB-each alloc reclaims ~1MB VRAM, so the blur build uses LESS VRAM than the validated lens build.
    // The cloak's 16×16 FBs (w<200) still allocate below; re-enable the full-frame RTs only when the
    // render-TO-FB menu blur increment actually needs one (§7.1).
    if (render_target && w >= 200) {
        if (f->texInit) { C3D_TexDelete(&f->tex); f->texInit = false; }
        f->potW = potW; f->potH = potH; f->w = (uint16_t)w; f->h = (uint16_t)h;
        f->renderTarget = render_target; f->hasDepth = depth;
#if PD_DEBUG3DS
        { char b[96]; snprintf(b, sizeof(b), "FBALLOC fb=%d %ux%u SKIPPED (full-frame, unused on 3DS)", fb, (unsigned)w, (unsigned)h); plat3dsBootLog(b); }
#endif
        return;
    }
    if (f->texInit) C3D_TexDelete(&f->tex);
    bool ok = render_target ? C3D_TexInitVRAM(&f->tex, potW, potH, GPU_RGBA8)
                            : C3D_TexInit(&f->tex, potW, potH, GPU_RGBA8);
    f->texInit = ok;
    if (ok) {
        C3D_TexSetFilter(&f->tex, GPU_LINEAR, GPU_LINEAR);
        C3D_TexSetWrap(&f->tex, GPU_CLAMP_TO_EDGE, GPU_CLAMP_TO_EDGE);
        f->potW = potW; f->potH = potH;
    }
    f->w = (uint16_t)w; f->h = (uint16_t)h; f->renderTarget = render_target; f->hasDepth = depth;
#if PD_DEBUG3DS
    { char b[96]; snprintf(b, sizeof(b), "FBALLOC fb=%d %ux%u pot=%ux%u rt=%d ok=%d", fb, (unsigned)w, (unsigned)h, potW, potH, (int)render_target, (int)ok);
      plat3dsBootLog(b); }
#endif
}
