static void setupPipeline(void) {
    C3D_BindProgram(&sShaderProg);
    C3D_AttrInfo *ai = C3D_GetAttrInfo();
    AttrInfo_Init(ai);
    AttrInfo_AddLoader(ai, 0, GPU_FLOAT, 4); // pos
    AttrInfo_AddLoader(ai, 1, GPU_FLOAT, 2); // uv
    AttrInfo_AddLoader(ai, 2, GPU_FLOAT, 4); // rgba
    C3D_BufInfo *bi = C3D_GetBufInfo();
    BufInfo_Init(bi);
    BufInfo_Add(bi, sVbo, VBO_FLOATS_PER_VTX * sizeof(float), 3, 0x210);
    C3D_CullFace(GPU_CULL_NONE); // Fast3D handles winding
    // Literal-source white texture on the always-free unit 2 (see sWhiteTex).
    if (sWhiteTexOk)
        C3D_TexBind(2, &sWhiteTex);
}

static void gfx_citro3d_init(void) {
    sShaderDVLB = DVLB_ParseFile((u32 *)gfx_citro3d_shbin, gfx_citro3d_shbin_size);
    shaderProgramInit(&sShaderProg);
    shaderProgramSetVsh(&sShaderProg, &sShaderDVLB->DVLE[0]);
    sUniTransform = shaderInstanceGetUniformLocation(sShaderProg.vertexShader, "transform");

    // ★ OG-3DS LOMEM: an Old 3DS runs the CIA in the regular 64MB Application slice (no HIMEM — the 96MB
    // grant crashes some OG HOME menus), so the GPU/linear heap is tight. Store textures 16-bit to halve
    // their FCRAM and fit the budget. A New 3DS (124MB via SystemModeExt) keeps full RGBA8. (APT is up by
    // the time gfx init runs, unlike __system_allocateHeaps which must infer the tier from the heap size.)
    { bool isN3ds = false; APT_CheckNew3DS(&isN3ds); sLomem = !isN3ds; }

    // Fog master toggle (sdmc fog.txt, default ON) — read once so the user can A/B distance fog on HW.
    { FILE *fg = fopen("sdmc:/3ds/perfectdark/fog.txt", "r");
      if (fg) { int v = 1; if (fscanf(fg, "%d", &v) == 1) sFogEnable = (v != 0); fclose(fg); } }
    // Memory log (turok.cfg `memlog 1`, needs `debug 1`) — lightweight production diagnostic for the
    // FCRAM/linear-heap pressure that drops alpha textures (spiderwebs/projectile sprites render opaque)
    // then wedges the GPU. Emits the MEM heartbeat (linFreeKB/linMinKB/texOOM) ~1×/sec, no per-draw cost.
    { extern int g_cfg_memlog; if (g_cfg_memlog) sMemLog = true; }
    // §21.11 tex_lod mips A/B — read once at init so it works in PRODUCTION (was debug-only). texlodmips.txt=0
    // turns OFF the general-texture mip chains (the suspect for the real-HW "blurry textures" over-blur).
    { FILE *tl = fopen("sdmc:/3ds/perfectdark/texlodmips.txt", "r");
      if (tl) { int v = 1; if (fscanf(tl, "%d", &v) == 1) sTexLodMips = (v != 0); fclose(tl); } }
    // MASTER mips switch — BK default ON (PC-parity for tex_lod textures; see sMipsEnabled).
    // mips.txt=0 turns them off for A/B. The banjo SD path wins over the legacy perfectdark one.
    { FILE *mp = fopen("sdmc:/3ds/perfectdark/mips.txt", "r");
      if (mp) { int v = 1; if (fscanf(mp, "%d", &v) == 1) sMipsEnabled = (v != 0); fclose(mp); } }
    { FILE *mp = fopen("sdmc:/3ds/banjo/mips.txt", "r");
      if (mp) { int v = 1; if (fscanf(mp, "%d", &v) == 1) sMipsEnabled = (v != 0); fclose(mp); } }
    { FILE *mn = fopen("sdmc:/3ds/banjo/mipnearest.txt", "r");
      if (mn) { int v = 0; if (fscanf(mn, "%d", &v) == 1) sMipNearest = (v != 0); fclose(mn); } }
    // Facade bake A/B — read once at init so it works in PRODUCTION (the per-frame read below is PD_DEBUG3DS-only).
    // autobake.txt=0 turns the bake OFF (facades render RAW = the §20 stripe). Used to A/B whether the bakes were
    // really needed under memory pressure now that ROM streaming (§33) frees ~32 MB. Read BEFORE the OG gate so
    // OG still forces bakes off regardless.
    { FILE *ab2 = fopen("sdmc:/3ds/perfectdark/autobake.txt", "r");
      if (ab2) { int v = 1; if (fscanf(ab2, "%d", &v) == 1) sAutoBake = (v != 0); fclose(ab2); } }

    // 8x8 all-white RGBA8 (PICA minimum size) for the unit-2 literal source.
    // Linear-heap data → plain CPU memset is safe (NOT VRAM), then flush.
    if (C3D_TexInit(&sWhiteTex, 8, 8, GPU_RGBA8) && sWhiteTex.data) {
        memset(sWhiteTex.data, 0xFF, 8 * 8 * 4);
        GSPGPU_FlushDataCache(sWhiteTex.data, 8 * 8 * 4);
        C3D_TexSetFilter(&sWhiteTex, GPU_NEAREST, GPU_NEAREST);
        C3D_TexSetWrap(&sWhiteTex, GPU_REPEAT, GPU_REPEAT);
        sWhiteTexOk = true;
    }

    sVbo = (float *)linearAlloc(VBO_BYTES);
    sTexScratch = (uint32_t *)linearAlloc(TEX_SCRATCH_TEXELS * sizeof(uint32_t));
    sMipLin0 = (uint32_t *)linearAlloc(MIP_LIN_TEXELS * sizeof(uint32_t)); // bake tiling + mip box-filter
    sMipLin1 = (uint32_t *)linearAlloc(MIP_LIN_TEXELS * sizeof(uint32_t));
    BK_TR(BK_TR_BUFFER, "init sVbo=%p texScratch=%p mip0=%p mip1=%p linFreeKB=%u%s",
          (void *)sVbo, (void *)sTexScratch, (void *)sMipLin0, (void *)sMipLin1,
          (unsigned)(linearSpaceFree() >> 10),
          (!sVbo || !sTexScratch || !sMipLin0 || !sMipLin1) ? " NULL!" : "");

    for (int i = 0; i < TEX_POOL_SIZE; i++) {
        sTexValid[i] = false; sTexScaleS[i] = 1.f; sTexScaleT[i] = 1.f;
        sTexTilesS[i] = false; sTexTilesT[i] = false;
        sBakeSrc[i] = NULL; sBakeSrcW[i] = 0; sBakeSrcH[i] = 0; sBakeHash[i] = 0;
    }
    for (int i = 0; i < BAKE_CAP; i++) { sReg[i].hash = 0; sReg[i].slot = -1; }

    // ★ §32.5: gate the facade bake OFF on OG-3DS (covers the sync-bake build; the async worker self-gates in
    // bakeThreadStart). OG can't afford the bake pool RAM → facades render RAW (the §20 stripe, acceptable on
    // the compromise tier). New-3DS keeps the bake. [Provisional — OG untested without hardware.]
    { bool n3 = false; APT_CheckNew3DS(&n3); if (!n3) sAutoBake = 0; }

    /* turok.cfg `bake` toggle. DEFAULT 0 (off) for Turok: its organic outdoor art rarely hits the
     * PICA tiled-UV precision case the bake fixes (unlike PD's tiled corridors; cf. sm64-port, which
     * bakes nothing). `bake 1` re-enables the async facade bake on the spare core. */
    { extern int g_cfg_bake; if (!g_cfg_bake) sAutoBake = 0; }
    /* turok.cfg stereo_z / stereo_w — on-device tuning of the 3D shear without a rebuild
     * (stereo is only visible on real hardware; -1 = use the compiled defaults). */
    { extern float g_cfg_stereo_z, g_cfg_stereo_w;
      if (g_cfg_stereo_z >= 0.f) sShearZ = g_cfg_stereo_z;
      if (g_cfg_stereo_w >= 0.f) sShearW = g_cfg_stereo_w; }
    /* turok.cfg stereo_strength — scale BOTH shear terms together (more/less POP, convergence plane fixed);
     * stereo_swap — invert the eye sign (pseudoscopic fix). Both default to the compiled look (1.0 / off). */
    { extern float g_cfg_stereo_strength; extern int g_cfg_stereo_swap;
      if (g_cfg_stereo_strength > 0.f) { sShearZ *= g_cfg_stereo_strength; sShearW *= g_cfg_stereo_strength; }
      sEyeSwap = g_cfg_stereo_swap ? -1.0f : 1.0f; }
#if PD_BAKE_THREAD
    if (sAutoBake) bakeThreadStart();   // only spin up the worker (+ its linearAlloc scratch) when baking is on
#endif
    setupPipeline();
}

